# ============================================================================
# seeds.rb — 初期データの投入
#
# 【seed（種）とは】
#   アプリを動かすために最初から必要なデータを作るスクリプト。
#   `rails db:seed` で実行される。
#
# 【このアプリでの用途】
#   ユーザー登録画面を作らない方針なので（1人用のため）、
#   自分のアカウントをここで1件だけ作る。
#
# 【冪等性（べきとうせい）を保つこと】← seedを書くときの鉄則
#   冪等とは「何回実行しても結果が同じ」という性質。
#
#   User.create! と書くと、2回目の実行でメールアドレスが重複して落ちる。
#   find_or_create_by! なら「無ければ作る、有れば何もしない」なので、
#   何度実行しても安全。
#
#   なぜ重要か: seedは「DBを作り直したとき」「本番へデプロイしたとき」
#   「テストの準備」など、様々な場面で繰り返し実行される。
#   1回しか流せないスクリプトは、そのたびに手作業が必要になる。
#
#   ちなみに「冪等性」は、あなたが最初に例として挙げた単語でもある。
#   このアプリで最初に登録して、AIに解説させてみてほしい。
# ============================================================================

# ----------------------------------------------------------------------------
# 環境変数から読む
# ----------------------------------------------------------------------------
# 【なぜここにメールとパスワードを直接書かないのか】
#   このファイルはGitにコミットされる。
#   パスワードを直書きすると、リポジトリを見た人全員に知られる。
#   一度コミットすると履歴に残り続けるため、後から消しても手遅れ。
#
#   環境変数から読む形にしておけば、
#   ・ローカルでは .env の値
#   ・本番では Fly.io の secrets の値
#   と、コードを1文字も変えずに別の値を使える。
email    = ENV.fetch("SEED_USER_EMAIL", nil)
password = ENV.fetch("SEED_USER_PASSWORD", nil)

# ----------------------------------------------------------------------------
# 設定漏れのチェック
# ----------------------------------------------------------------------------
# 【なぜ黙って既定値を使わないのか】← 安全側に倒す判断
#   ここで password ||= "password123" のような既定値を用意すると、
#   設定を忘れたまま本番にデプロイしたとき、
#   誰でも推測できるパスワードのアカウントが
#   インターネット上に公開されてしまう。
#
#   気付かないまま危険な状態になるより、
#   はっきり止まって気付かせる方が良い。
if email.blank? || password.blank?
  abort <<~MESSAGE
    [seed中止] SEED_USER_EMAIL と SEED_USER_PASSWORD が設定されていません。

    .env ファイルに以下を設定してください:
      SEED_USER_EMAIL=あなたのメールアドレス
      SEED_USER_PASSWORD=12文字以上のパスワード

    .env が無い場合は .env.example をコピーして作成してください:
      cp .env.example .env
  MESSAGE
end

# ----------------------------------------------------------------------------
# ユーザーを作成（既に居れば何もしない）
# ----------------------------------------------------------------------------
# 【find_or_create_by! の動き】
#   ① email が一致するユーザーを探す
#   ② 居ればそれを返す（ブロックは実行されない）
#   ③ 居なければ新規作成し、ブロックの中で追加の属性を設定する
#
# 【末尾の ! について】Rubyの慣習で「失敗したら例外を投げる」の印。
#   ! が無い版は失敗時に false を返すだけなので、
#   検証エラーで作られなかったことに気付かないまま処理が進んでしまう。
#   seedは「確実に作られたこと」が前提の処理なので、
#   失敗したら止まってほしい。だから ! を使う。
user = User.find_or_create_by!(email: email) do |u|
  # 【この代入で何が起きているか】
  #   password= は has_secure_password が作った仮想の属性。
  #   代入した瞬間にbcryptでハッシュ化され、
  #   password_digest カラムに入る。
  #   平文の password はメモリ上にあるだけで、DBには保存されない。
  u.password = password
end

puts "ユーザーを用意しました: #{user.email} (id=#{user.id})"
puts "  password_digest = #{user.password_digest[0, 30]}..."
puts ""
puts "  ↑ この文字列の読み方:"
puts "     $2a$  … bcryptというアルゴリズムを使った印"
puts "     $12$  … 2の12乗(4096)回 計算を繰り返す設定（わざと遅くしている）"
puts "     以降  … ソルト(22文字) + ハッシュ値"
puts ""
puts "  同じパスワードでも、ソルトが毎回違うため保存される値は毎回変わります。"
puts "  試しに rails db:seed をもう一度実行しても、"
puts "  既にユーザーが居るので作り直されない（冪等）ことも確認できます。"
