# ============================================================================
# api_call_logs テーブル — Claude API を呼んだ記録
#
# Q4で「実務レベルのハーネス」を選んだことで必要になったテーブル。
#
# 【なぜ記録するのか】3つの用途がある。
#
#   ① コストが見える
#      「今月いくら使ったか」がSQL 1本で分かる。
#      AIアプリで最も怖いのは、想定外の課金に気付かないこと。
#      無限リトライのバグを1晩放置すると、数万円に達する例がある。
#
#   ② プロンプト改善の効果が測れる
#      prompt_version を記録しておけば、
#      「v1とv2でトークン量・失敗率・所要時間がどう変わったか」を
#      数字で比較できる。
#      これが無いと「なんとなく良くなった気がする」で終わる。
#
#   ③ 障害の原因が追える
#      「昨日から解説が失敗する」と気付いたとき、
#      error_class を見れば、レート制限なのか、認証切れなのか、
#      タイムアウトなのかが即座に分かる。
#      ログが無いと、再現しないと調べられない。
# ============================================================================
class CreateApiCallLogs < ActiveRecord::Migration[8.1]
  def change
    create_table :api_call_logs do |t|
      # ----------------------------------------------------------------------
      # どの単語の生成だったか
      # ----------------------------------------------------------------------
      # 【null: true にしている理由】
      #   単語が削除されても、呼び出しの記録は残したい。
      #   「今月いくら使ったか」の集計は、
      #   その後に単語を消したかどうかとは無関係だからだ。
      #
      #   後述の on_delete: :nullify と組み合わせて、
      #   単語が消えたら term_id だけ NULL になり、行自体は残る。
      #
      # 【設計の考え方】
      #   会計・監査の性格を持つ記録は、原則として消さない。
      #   参照先が消えたら「参照を外す」だけにして、
      #   事実そのものは保存し続ける。
      t.references :term, null: true, foreign_key: { on_delete: :nullify }

      # ----------------------------------------------------------------------
      # 使ったモデルとプロンプトのバージョン
      # ----------------------------------------------------------------------
      # 例: "claude-opus-4-8"
      # 【なぜ記録するか】将来モデルを変えたとき、
      #   「切り替え前後で品質とコストがどう変わったか」を比較できる。
      t.string :model, null: false

      # 例: "explain_term_v1"
      # 【なぜプロンプトにバージョンを付けるか】
      #   プロンプトはコードと同じく改良を重ねるもの。
      #   どの版で生成された結果なのかが分からないと、
      #   「この単語の解説が変なのは、古い版のせいなのか」を
      #   判断できなくなる。
      t.string :prompt_version, null: false

      # ----------------------------------------------------------------------
      # トークン数
      # ----------------------------------------------------------------------
      # 【トークンとは】AIが文章を扱う単位。単語よりやや細かい。
      #   日本語だと 1文字 ≒ 1トークン程度が目安。
      #   課金はこのトークン数で決まる。
      #
      # 【入力と出力を分けて持つ理由】単価が違う。
      #   Opus 4.8 では 入力 $5 / 出力 $25（100万トークンあたり）。
      #   出力の方が5倍高いので、合算してしまうと
      #   「どちらを削れば効くのか」が分からなくなる。
      t.integer :input_tokens,  null: false, default: 0
      t.integer :output_tokens, null: false, default: 0

      # ----------------------------------------------------------------------
      # かかった金額
      # ----------------------------------------------------------------------
      # 【なぜ「マイクロUSD」という単位なのか】← 金額を扱う鉄則
      #
      #   1マイクロUSD = 0.000001ドル。整数で保存する。
      #
      #   金額を float（小数）で保存してはいけない。
      #   コンピュータの小数は2進数なので、0.1 のような値を
      #   正確に表現できない。実際にRubyで試すと:
      #
      #     0.1 + 0.2        # => 0.30000000000000004
      #     (0.1 + 0.2) == 0.3  # => false
      #
      #   1件ならごく僅かな誤差だが、何千件も足し合わせると
      #   合計が合わなくなる。「1円合わない」の典型的な原因。
      #
      #   整数なら誤差は原理的に発生しない。
      #   表示するときだけ 1_000_000 で割ればよい。
      #
      #   【一般則】金額・数量など「合計して意味を持つ値」は、
      #   最小単位の整数で保存する。
      #   （日本円なら「銭」、ドルなら「セント」や「マイクロドル」）
      t.integer :cost_micro_usd, null: false, default: 0

      # ----------------------------------------------------------------------
      # 所要時間（ミリ秒）
      # ----------------------------------------------------------------------
      # 【何に使うか】
      #   ・体感速度の把握（実際に何秒待たされているのか）
      #   ・異常の検知（急に10倍遅くなった＝API側の障害の可能性）
      #   ・効果測定（プロンプトを短くしたら速くなったか）
      t.integer :latency_ms, null: false, default: 0

      # ----------------------------------------------------------------------
      # 成否と失敗理由
      # ----------------------------------------------------------------------
      # 成功したかどうか。
      t.boolean :success, null: false, default: false

      # 失敗した場合の例外クラス名。
      # 例: "Anthropic::Errors::RateLimitError"
      #
      # 【なぜメッセージ本文ではなくクラス名を持つのか】
      #   メッセージは可変で、集計に使えない。
      #   クラス名なら GROUP BY で
      #   「レート制限が何回、タイムアウトが何回」と数えられる。
      #   （詳細な本文は error_detail に入れる）
      t.string :error_class

      # 失敗時の詳細。原因を追うときに読む。
      t.text :error_detail

      # 何回目の試行か（リトライの記録）。
      # 【なぜ必要か】「1回で成功」と「3回目でようやく成功」は
      #   同じ成功でも意味が全く違う。
      #   後者が増えていれば、API側が不安定になっている兆候。
      t.integer :attempt, null: false, default: 1

      # 【created_at だけで updated_at を持たない】
      #   ログは書いたら書き換えない（追記のみ）。
      #   更新しないカラムを持つと、
      #   「更新してもいいのかな」と読み手を迷わせる。
      #   持たないこと自体が「これは不変の記録だ」という意思表示になる。
      t.datetime :created_at, null: false
    end

    # ------------------------------------------------------------------------
    # 集計用インデックス
    # ------------------------------------------------------------------------
    # 「今月の合計コスト」「直近の失敗一覧」を出すとき、
    # created_at で範囲を絞って並べるので、この索引が効く。
    add_index :api_call_logs, :created_at

    # 「失敗だけ抽出する」ときに効く索引。
    add_index :api_call_logs, [ :success, :created_at ]
  end
end
