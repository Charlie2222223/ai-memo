# ============================================================================
# terms に「読み方」と「正式名称・英語表記」を足す
#
# ----------------------------------------------------------------------------
# 【なぜ必要か】
# ----------------------------------------------------------------------------
#   単語帳として使うとき、意味だけ分かっても口に出せない語がある。
#
#     API   … エーピーアイ / Application Programming Interface
#     冪等性 … べきとうせい / idempotency
#     CORS  … コルス / Cross-Origin Resource Sharing
#
#   「冪」のような読めない漢字や、何の略か分からない頭字語は、
#   意味を理解しても会話や検索で使えないまま終わる。
#   このアプリの目的は「調べる手間を消す」ことなので、
#   読み方を別途調べさせるのは目的に反する。
#
# ----------------------------------------------------------------------------
# 【なぜ meaning に含めさせないのか】
# ----------------------------------------------------------------------------
#   「APIとは、エーピーアイと読み、Application Programming Interface の略で…」
#   と本文に混ぜることもできる。しかしそうすると:
#     ・一覧の1行要約が読み方の説明で埋まる
#     ・読み方だけ知りたいときに本文を読む必要がある
#     ・書式がAIの気分で揺れる（括弧だったり読点だったり）
#
#   独立したカラムにすれば、見出しの下に固定の位置で出せる。
#   構造化できる情報は本文に混ぜない。
#
# ----------------------------------------------------------------------------
# 【なぜ null 許可なのか】
# ----------------------------------------------------------------------------
#   該当しない語が普通にある。
#     「プリフライト」… 既にカタカナなので読み方は不要
#     「設計」        … 略語ではないので正式名称は無い
#   無理に埋めさせると、AIが不自然な値を捏造する。
#   空のまま置ける方が正直な設計になる。
# ============================================================================
class AddReadingToTerms < ActiveRecord::Migration[8.1]
  def change
    # 読み方（かな）。「べきとうせい」「エーピーアイ」など。
    add_column :terms, :reading, :string

    # 正式名称または対応する英語表記。
    # 【1カラムに2つの意味を持たせている理由】
    #   頭字語の展開（API → Application Programming Interface）と、
    #   和語に対応する英語（冪等性 → idempotency）は、
    #   利用者から見ればどちらも「元の言葉は何か」という同じ問い。
    #   分けると、どちらに入るのか判断が必要になり、
    #   画面でも2つの空欄を出し分けることになる。
    add_column :terms, :full_form, :string
  end
end
