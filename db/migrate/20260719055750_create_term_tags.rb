# ============================================================================
# term_tags テーブル — 単語とタグを結ぶ「中間テーブル」
#
# ★ ER設計を学ぶ上で、このテーブルが最大の山場です。
#
# ----------------------------------------------------------------------------
# 【なぜ中間テーブルが必要なのか】
# ----------------------------------------------------------------------------
#   表現したい関係は「多対多」:
#     ・1つの単語に複数のタグを付けたい
#         「冪等性」→ [API設計] [インフラ]
#     ・1つのタグが複数の単語に付く
#         [インフラ] → 「冪等性」「ロードバランサ」「コンテナ」
#
#   これを2つのテーブルだけで表そうとすると、必ず破綻する。
#
#   ■ 失敗案A: terms に tag_id カラムを持つ
#       terms
#       ┌────┬──────────┬────────┐
#       │ id │ word     │ tag_id │
#       ├────┼──────────┼────────┤
#       │  1 │ 冪等性   │      3 │  ← 1つしか付けられない
#       └────┴──────────┴────────┘
#       → 「API設計」と「インフラ」の両方を付けられない。
#
#   ■ 失敗案B: terms に tag_ids カラムをカンマ区切りで持つ
#       │  1 │ 冪等性   │ "3,7"  │
#       → 一見動くが、実務では確実に苦しむ:
#          ・「タグ3が付いた単語」を探すのに LIKE '%3%' が必要
#            → タグ13、23、30 も引っかかる
#          ・索引が使えないので、件数が増えると急激に遅くなる
#          ・存在しないタグIDを書いても、DBは検知できない
#          ・タグを消したとき、この文字列の中の値は残り続ける
#
#   ■ 正解: 関係そのものを1つのテーブルにする
#       term_tags
#       ┌─────────┬────────┐
#       │ term_id │ tag_id │
#       ├─────────┼────────┤
#       │       1 │      3 │  ← 冪等性 に API設計
#       │       1 │      7 │  ← 冪等性 に インフラ
#       │       2 │      7 │  ← コンテナ に インフラ
#       └─────────┴────────┘
#
#       1行 = 「この単語にこのタグが付いている」という1つの事実。
#       何個でも足せるし、どちらの方向からも索引で高速に引ける。
#
# ----------------------------------------------------------------------------
# 【一般化: 多対多は必ず中間テーブルになる】
# ----------------------------------------------------------------------------
#   ・学生 と 授業 → 履修
#   ・記事 と タグ → 記事タグ
#   ・ユーザー と グループ → 所属
#
#   実務で出会うER図は、ほぼこの形の組み合わせでできている。
#   「多対多を見たら中間テーブル」と反射で出てくるようにしておくと、
#   設計で迷う場面が大きく減る。
# ============================================================================
class CreateTermTags < ActiveRecord::Migration[8.1]
  def change
    create_table :term_tags do |t|
      # 【両方に外部キー制約を張る】
      #   存在しない単語やタグを指す行が作られないようにする。
      #   さらに、タグを削除しようとしたとき
      #   「まだ使われている」とDBが止めてくれる。
      t.references :term, null: false, foreign_key: true
      t.references :tag,  null: false, foreign_key: true

      # 【中間テーブルに timestamps を持たせるか】
      #   持たせない設計も多いが、ここでは持たせる。
      #   「いつこのタグが付いたか」は後から知りたくなることがあり、
      #   後から足すより最初から入れておく方が安い。
      t.timestamps
    end

    # ------------------------------------------------------------------------
    # 同じ組み合わせを2回作らせない
    # ------------------------------------------------------------------------
    # 【なぜ必要か】
    #   同じ単語に同じタグを2回付けると、
    #   ・画面にタグが二重表示される
    #   ・JOINした一覧で単語が2行に増える（重複行）
    #   といった、原因が分かりにくい表示崩れが起きる。
    #
    # 【中間テーブルには必ずこの制約を張る】
    #   多対多の中間テーブルで最も忘れられやすく、
    #   最も高い確率でバグを生む箇所。
    #   「中間テーブルを作ったら複合ユニーク」もセットで覚えるとよい。
    add_index :term_tags, [ :term_id, :tag_id ], unique: true

    # ------------------------------------------------------------------------
    # 逆方向の検索用インデックス
    # ------------------------------------------------------------------------
    # 【なぜ tag_id 単独の索引が別に要るのか】
    #   上の複合索引は (term_id, tag_id) の順なので、
    #   左端が term_id。つまり
    #     ・「この単語のタグ一覧」        → 上の索引が効く
    #     ・「このタグが付いた単語の一覧」→ 効かない（左端が違う）
    #
    #   このアプリの主な使い方は
    #   「[インフラ] を選んで絞り込む」＝ tag_id からの検索なので、
    #   こちらの索引が実際には一番よく使われる。
    #
    #   なお t.references が tag_id の索引を自動で作るため、
    #   厳密にはこの行は重複する。
    #   それでも明示するのは、「なぜこの向きの索引が要るのか」を
    #   コードに残すため。
    #   （重複索引は容量の無駄になるので、実務では
    #     references 側の index: false と組み合わせて調整する）
  end
end
