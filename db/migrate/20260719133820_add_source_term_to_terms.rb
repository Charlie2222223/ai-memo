# ============================================================================
# terms に「どの単語の解説から調べたか」を記録するカラムを足す
#
# ----------------------------------------------------------------------------
# 【何のためのカラムか】
# ----------------------------------------------------------------------------
#   解説を読んでいて分からない語が出てきたとき、その場で選択して
#   解説させられるようにした。そうやって生まれた単語には
#   「どこで見かけたか」という出自がある。
#
#     CORS の解説 → 「プリフライト」を選択して登録
#                    → プリフライト.source_term = CORS
#
#   これを持つと、
#     子から親へ … 読んでいた場所に戻れる
#     親から子へ … その解説から何を掘り下げたかが見える
#   の両方ができる。
#
# ----------------------------------------------------------------------------
# 【context に文章で残るのに、なぜカラムも要るのか】
# ----------------------------------------------------------------------------
#   context には「「CORS」の解説内で見た」という文字列が入る。
#   人間が読む分にはこれで足りるが、文字列なので
#     ・クリックして親へ移動する
#     ・親から子の一覧を引く
#   ができない。文字列を解析して単語を探すのは、
#   親の名前が変わった瞬間に壊れる。
#
#   関係そのものを表現したいなら、外部キーで持つのが正しい。
#
# ----------------------------------------------------------------------------
# 【自己参照（同じテーブルを指す外部キー）】
# ----------------------------------------------------------------------------
#   terms の行が terms の別の行を指す。木構造を表す定番の形。
#
#   to_table: :terms を明示しているのは、カラム名が source_term_id で
#   テーブル名（terms）と一致しないため。
#   Railsは名前から参照先を推測するので、
#   これが無いと source_terms という存在しないテーブルを探しに行く。
# ============================================================================
class AddSourceTermToTerms < ActiveRecord::Migration[8.1]
  def change
    # 【on_delete: :nullify にする理由】← フォルダのときと同じ判断
    #   親を削除したときに子まで消えると、
    #   1件3.4円かけて生成した解説が巻き添えで失われる。
    #
    #   利用者の意図は「この単語は要らない」であって
    #   「ここから派生した単語も全部要らない」ではない。
    #   親が消えたら、子は「出自不明の単語」として残ればよい。
    #
    #   既定（restrict）だと、子を持つ単語が削除できなくなる。
    #   何を消せば消せるようになるのか画面から分からず、詰む。
    add_reference :terms, :source_term,
                  null: true,
                  foreign_key: { to_table: :terms, on_delete: :nullify }
  end
end
