class CreateTags < ActiveRecord::Migration[8.1]
  def change
    create_table :tags do |t|
      # ----------------------------------------------------------------------
      # 【なぜタグにも user_id が要るのか】
      # ----------------------------------------------------------------------
      #   今は1人用なので、無くても動く。
      #   それでも付ける理由は2つ。
      #
      #   ① 将来ユーザーが増えたとき、タグが全員で共有されると困る。
      #      あなたの「インフラ」と他人の「インフラ」は
      #      同じ言葉でも指す範囲が違う。
      #      後からこのカラムを足すのは、既存データの割り当てが
      #      必要になって非常に面倒。
      #
      #   ② 権限チェックが構造的に効くようになる。
      #      current_user.tags と書けば、他人のタグは絶対に混ざらない。
      #      user_id が無いと、タグ一覧APIで
      #      「全員のタグが見える」実装を書いてしまいやすい。
      #
      #   【設計判断】「今は要らないが、後から足すのが高くつく」ものは
      #   最初に入れておく。逆に「後から足すのが安いもの」は
      #   必要になるまで作らない（Q9で復習機能を見送ったのはこの逆）。
      t.references :user, null: false, foreign_key: true

      t.string :name, null: false

      t.timestamps
    end

    # ------------------------------------------------------------------------
    # 同じユーザー内でタグ名を一意にする
    # ------------------------------------------------------------------------
    # 【なぜ必要か】「Rails」というタグが2つできると、
    #   絞り込みが分裂して、どちらを選んでも全部は出てこなくなる。
    #
    # 【AIに自動でタグを付けさせる場合に特に効く】
    #   AIは「Rails」「rails」「RAILS」のような揺れを生む。
    #   モデル側で正規化した上で、ここで最終的な重複を止める。
    add_index :tags, [ :user_id, :name ], unique: true
  end
end
