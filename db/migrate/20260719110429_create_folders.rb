# ============================================================================
# folders テーブル — 単語の置き場所
#
# 例:「Web・HTTP」「DB・データ」「設計」
#
# ----------------------------------------------------------------------------
# 【タグがあるのに、なぜフォルダを別に作るのか】← 最初に浮かぶ疑問
# ----------------------------------------------------------------------------
#   タグは既にあり、AIが自動で付けている。しかし用途が違う。
#
#     タグ     … 1単語に複数（実測で平均3個）。重なり合う。細かい
#     フォルダ … 1単語に1つ。排他。少数で安定
#
#   実測すると、単語3件でユニークなタグは6個だった。
#   この比率のまま30件になれば40〜50個に膨らむ。
#   サイドバーに並べても探せる数ではなく、
#   ナビゲーションとしては破綻する。
#
#   「絞り込んで辿る」には、件数が増えても増えない軸が要る。
#   それがフォルダ。タグは検索と、詳細画面での分類の手掛かりとして残す。
#
# ----------------------------------------------------------------------------
# 【なぜ terms に文字列カラムを足すのではなく、テーブルにするのか】
# ----------------------------------------------------------------------------
#   フォルダ名は利用者が自由に変更できる仕様にした。
#   文字列で持つと、名前を変えるたびに該当する全レコードを
#   書き換える必要があり、途中で失敗すると表記が分裂する。
#
#   テーブルに分けて外部キーで参照すれば、
#   folders の1行を書き換えるだけで全単語の表示が変わる。
#   これが正規化の実利。
# ============================================================================
class CreateFolders < ActiveRecord::Migration[8.1]
  def change
    create_table :folders do |t|
      # 【user_id を必ず持たせる理由】tags と同じ。
      #   current_user.folders と書けるようにしておくことで、
      #   他人のフォルダが混ざる余地を構造的に無くす。
      t.references :user, null: false, foreign_key: true

      t.string :name, null: false

      t.timestamps
    end

    # ------------------------------------------------------------------------
    # 同じユーザー内でフォルダ名を一意にする
    # ------------------------------------------------------------------------
    # 【AIに提案させる場合に特に効く】
    #   AIは「Web・HTTP」と「Web/HTTP」のような揺れを生む。
    #   モデル側で正規化し、大文字小文字を無視して既存を探した上で、
    #   最後の砦としてDBにも制約を置く。
    #
    #   アプリ側のチェックだけだと、同時に2件登録されたときに
    #   両方が「まだ無い」と判断してすり抜ける（競合状態）。
    #   DBの制約はその場合も必ず止められる。
    add_index :folders, [ :user_id, :name ], unique: true
  end
end
