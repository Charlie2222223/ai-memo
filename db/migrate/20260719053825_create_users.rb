#
# 【マイグレーションとは】
#   DBの構造（テーブル・カラム・インデックス）を変更する手順書。
#   ファイル名の先頭の数字（20260719053825）は作成日時で、
#   Railsはこの順番で未適用のものを実行していく。
#
# 【なぜ手でSQLを書かずにこれを使うのか】
#   ① 順番と適用済みかどうかをRailsが管理してくれる
#      → 別のPCや本番サーバーでも、同じ手順が同じ順で再現される
#   ② Ruby で書けるので、DBの種類（PostgreSQL/MySQL）に依存しにくい
#   ③ 変更の履歴がコードとしてGitに残る
#      → 「いつ誰がこのカラムを足したか」が追える
# ============================================================================
