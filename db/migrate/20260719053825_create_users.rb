    create_table :users do |t|
      # ----------------------------------------------------------------------
      # メールアドレス（ログインIDとして使う）
      # ----------------------------------------------------------------------
      # null: false は「空を許さない」というDB側の制約。
      #
      # 【なぜモデル側の検証だけでは不十分か】← 重要な考え方
      #   Railsのモデルに validates presence: true と書いても、
      #   それはRubyのコードを通ったときにしか効かない。
      #   ・rails console から直接 insert された
      #   ・psql で手作業で入れた
      #   ・別の言語で書かれたバッチが入れた
      #   といった経路では素通りしてしまう。
      #
      #   DB側の制約は「どんな経路で来ても」必ず効く最後の砦。
      #   モデル側の検証は「ユーザーに親切なエラーを出す」ため、
      #   DB側の制約は「データを壊さない」ため。役割が違うので両方書く。
      t.string :email, null: false

      # ----------------------------------------------------------------------
      # パスワードのハッシュ値
      # ----------------------------------------------------------------------
      # 【カラム名が password ではなく password_digest である理由】
      #   Railsの has_secure_password は「password_digest」という
      #   名前のカラムがあることを前提に動く規約。
      #   この名前にしておくだけで、
      #     user.password = "秘密"     → 自動でハッシュ化して digest に保存
      #     user.authenticate("秘密")  → 照合
      #   が使えるようになる。名前が違うと動かない。
      #
      # 【digest（ダイジェスト）という言葉】
      #   「要約」の意味。元に戻せない要約値、というニュアンス。
      #   平文のパスワードは一切保存しない、という設計の宣言でもある。
      #
      #   保存される値の例:
      #     $2a$12$N9qo8uLOickgx2ZMRZoMye.IjPeKYb3sVjkR1FEbA3rTLQfaCz1Aq
      #      ~~~ ~~ ~~~~~~~~~~~~~~~~~~~~~~ ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
      #       │   │        │                          └ ハッシュ値
      #       │   │        └ ソルト（このユーザー専用のランダムな塩）
      #       │   └ コストパラメータ（2^12 = 4096回の計算を繰り返す）
      #       └ アルゴリズム識別子（2a = bcrypt）
      #
      #   ソルトが1人ずつ違うため、同じパスワードでも保存値は全員違う。
      #   → 「よくあるパスワードのハッシュ一覧表」による総当たりが効かない。
      t.string :password_digest, null: false

      # created_at と updated_at を自動で作る。
      # Railsがレコードの作成時・更新時に自動で入れてくれる。
      # 「いつ登録されたか」は後から必ず知りたくなるので、常に入れておく。
      t.timestamps
    end

    # ------------------------------------------------------------------------
    # メールアドレスの一意インデックス
    # ------------------------------------------------------------------------
    # 【unique: true の意味】同じメールアドレスを2人登録できなくする。
    #
    # 【なぜDB側で保証する必要があるか】← 実務で必ず出る話
    #   モデルに validates uniqueness: true と書くと、Railsは
    #   「保存する直前にSELECTして、既に居ないか確認する」という動きをする。
    #
    #   ところが同時に2人が登録した場合:
    #     時刻1  Aのリクエスト: SELECT → 居ない！
    #     時刻2  Bのリクエスト: SELECT → 居ない！
    #     時刻3  Aのリクエスト: INSERT → 成功
    #     時刻4  Bのリクエスト: INSERT → 成功（重複してしまった）
    #
    #   確認と挿入の間に隙間があるため、検証をすり抜ける。
    #   これを競合状態（race condition）と呼ぶ。
    #   DB側のユニーク制約なら、この隙間が存在しないので確実に防げる。
    #
    # 【インデックスとしての効果】
    #   ログイン時は必ず「このメールのユーザーを探す」検索をする。
    #   インデックスが無いと全件を上から順に見る（フルスキャン）が、
    #   インデックスがあれば辞書の索引のように直接引ける。
    #   ユニーク制約を張ると索引も同時に作られるので、一石二鳥。
    add_index :users, :email, unique: true
  end
end
