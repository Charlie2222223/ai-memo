# ============================================================================
# terms にフォルダ関連の2カラムを足す
#
# ----------------------------------------------------------------------------
# 【なぜ2つ要るのか】← 設計の要点
# ----------------------------------------------------------------------------
#   AIの分類結果には2種類ある。
#
#     ① 既存のフォルダに当てはまる  → folder_id に入れて確定
#     ② どれにも当てはまらない      → suggested_folder_name に「提案」として置く
#
#   ②を folder_id に直接入れて勝手にフォルダを作らないのは、
#   フォルダが際限なく増えてタグと同じ末路をたどるため。
#   新しいフォルダを作るかどうかは利用者が決める。
#
#   提案を保持する場所が無いと、承認するまで情報が失われる。
#   だから「確定した所属」と「未承認の提案」は別のカラムに分ける。
#
#   ①は黙って入れて通知だけ出す。②だけ承認を求める。
#   こうするとフォルダが育つほど②が減り、手間が自然に消えていく。
#   毎回承認を求める設計だと、単語が増えるほど作業が増えて逆行する。
# ============================================================================
class AddFolderToTerms < ActiveRecord::Migration[8.1]
  def change
    # ------------------------------------------------------------------------
    # 所属フォルダ
    # ------------------------------------------------------------------------
    # 【null: true にする理由】
    #   フォルダは空の状態から始める仕様なので、
    #   最初の単語はどこにも所属しない（＝未分類）。
    #   必須にすると1件も登録できなくなる。
    #
    # 【on_delete: :nullify にする理由】← ここを間違えると事故になる
    #   既定（restrict）だと、中身のあるフォルダを削除できない。
    #   cascade だと、フォルダを消した瞬間に中の単語が全部消える。
    #
    #   利用者の意図は「この分類をやめたい」であって
    #   「この単語たちを捨てたい」ではない。
    #   nullify なら単語は残り、未分類に戻るだけで済む。
    #
    #   AI生成に1件3.4円かかっている資産を、
    #   フォルダ整理の巻き添えで失わせてはいけない。
    add_reference :terms, :folder,
                  null: true,
                  foreign_key: { on_delete: :nullify }

    # ------------------------------------------------------------------------
    # AIが提案した新しいフォルダ名（未承認）
    # ------------------------------------------------------------------------
    # 【なぜ外部キーではなく文字列なのか】
    #   この時点ではまだフォルダとして存在していない。
    #   存在しないものを参照する外部キーは作れない。
    #
    #   承認された時点で folders に1行作り、folder_id を埋め、
    #   このカラムは nil に戻す。つまり一時的な置き場。
    add_column :terms, :suggested_folder_name, :string
  end
end
