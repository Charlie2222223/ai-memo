// ============================================================================
// application.js — Vueアプリの起動点（エントリーポイント）
//
// レイアウトの vite_javascript_tag 'application' がこのファイルを読み込む。
// ここから画面全体が組み上がる。
// ============================================================================
import { createApp } from 'vue'
import { createPinia } from 'pinia'
import App from '../App.vue'
import { router } from '../router'
import '../styles.css'

// ----------------------------------------------------------------------------
// アプリを組み立てる
// ----------------------------------------------------------------------------
// 【createApp(App)】App.vue を最上位のコンポーネントとしてアプリを作る。
const app = createApp(App)

// 【プラグインの登録】
//   .use() で機能を追加する。順序は問わない。
//   ・Pinia  … 状態管理（複数画面でデータを共有）
//   ・Router … URLと画面の対応付け
app.use(createPinia())
app.use(router)

// ----------------------------------------------------------------------------
// 描画先に差し込む
// ----------------------------------------------------------------------------
// 【'#app' とは】app/views/pages/index.html.erb にある
//   <div id="app"></div> のこと。
//   Vueはこの要素の中身を丸ごと自分の描画結果で置き換える。
//
// 【これがSPAの起点】
//   ここから先、ページ遷移もデータ取得もすべてブラウザの中で完結する。
//   サーバーへHTMLを取りに行くことは二度と無い（データはJSONで取る）。
app.mount('#app')
