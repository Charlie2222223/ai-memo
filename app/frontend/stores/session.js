// ============================================================================
// session.js — ログイン状態を保持するストア（Pinia）
//
// 【ストアとは】
//   複数の画面で共有したいデータを置く場所。
//
// 【なぜ必要か】
//   「今ログインしているのは誰か」は、
//   ヘッダー・一覧・詳細など複数の画面が知りたい情報。
//
//   コンポーネント間で受け渡そうとすると、
//   親 → 子 → 孫 と何段も引き渡すことになる（バケツリレー）。
//   途中の階層は使わないのに、受け取って渡すだけの記述が必要になる。
//
//   ストアに置けば、必要な場所が直接読める。
//
// 【Piniaとは】Vue公式の状態管理ライブラリ。
//   以前は Vuex が使われていたが、現在の推奨はこちら。
// ============================================================================
import { defineStore } from 'pinia'
import { ref, computed } from 'vue'
import { api } from '../lib/api'

export const useSessionStore = defineStore('session', () => {
  // --------------------------------------------------------------------------
  // 状態
  // --------------------------------------------------------------------------
  // 【ref とは】Vueが「値の変化を監視できる」箱。
  //   ただの変数 let user = null では、値を変えても画面は変わらない。
  //   ref で包むと、変更が自動的に画面へ反映される（リアクティブ）。
  //
  //   中身を読み書きするときは .value を付ける。
  //   （テンプレート内では自動で外れるので不要）
  const user = ref(null)

  // 起動直後の「まだ確認中」を表す。
  // 【なぜ必要か】これが無いと、確認が終わる前の一瞬だけ
  //   ログイン画面がちらつく（実際はログイン済みなのに）。
  const loading = ref(true)

  // --------------------------------------------------------------------------
  // 算出プロパティ
  // --------------------------------------------------------------------------
  // 【computed とは】他の値から自動的に導かれる値。
  //   user が変われば isLoggedIn も自動で変わる。
  //   毎回 user.value !== null と書くより意図が明確。
  const isLoggedIn = computed(() => user.value !== null)

  // --------------------------------------------------------------------------
  // アプリ起動時にログイン状態を確認する
  // --------------------------------------------------------------------------
  // 【なぜサーバーに聞く必要があるのか】
  //   セッションCookieは httpOnly なので、JavaScriptからは読めない。
  //   （XSS対策としてわざとそうしている）
  //   したがって「自分がログイン済みか」はブラウザ側では判断できず、
  //   サーバーに聞くしかない。
  //
  //   Cookie自体はブラウザが自動で送るので、
  //   このリクエストだけで判定できる。
  async function fetchSession() {
    try {
      const data = await api.getSession()
      user.value = data.user
    } catch {
      // 通信エラー等。未ログイン扱いにして進める。
      user.value = null
    } finally {
      // 【finally を使う理由】成功でも失敗でも必ず確認は終わる。
      //   ここで loading を false にしないと、
      //   通信に失敗したとき画面が永久にローディングのまま止まる。
      loading.value = false
    }
  }

  async function login(email, password) {
    const data = await api.login(email, password)
    user.value = data.user
  }

  async function logout() {
    await api.logout()
    user.value = null
  }

  return { user, loading, isLoggedIn, fetchSession, login, logout }
})
