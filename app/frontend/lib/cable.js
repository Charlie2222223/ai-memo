// ============================================================================
// cable.js — WebSocket（Action Cable）への接続
//
// 【役割】
//   Sidekiqワーカーが「解説ができた」と放送したものを受け取り、
//   画面のカードをリロードなしで更新する。
//
// 【全体の流れの、最後の1ピース】
//   [Sidekiq] 生成完了 → Redis(pub/sub) → [Rails] → ここ → 画面更新
// ============================================================================
import { createConsumer } from '@rails/actioncable'

// ----------------------------------------------------------------------------
// 接続の入口（Consumer）
// ----------------------------------------------------------------------------
// 【なぜ1つだけ作って使い回すのか】
//   WebSocketの接続はサーバー資源を消費する。
//   画面ごとに接続を作ると、画面を切り替えるたびに接続が増えていく。
//   1本の接続の中で複数のチャンネル（話題）を扱えるので、
//   接続自体は1つで足りる。
//
// 【引数を渡していない理由】
//   既定で /cable に繋ぐ。Q7で同一オリジンにしたので、
//   接続先を明示的に書く必要がない。
//   別オリジンなら 'wss://api.example.com/cable' のような
//   絶対URLを書く必要があり、環境ごとの分岐も生じる。
let consumer = null

function getConsumer() {
  if (!consumer) consumer = createConsumer()
  return consumer
}

// ----------------------------------------------------------------------------
// 単語の更新を購読する
// ----------------------------------------------------------------------------
// @param {Function} onUpdate 更新を受け取ったときに呼ばれる関数
// @returns {Object} 購読オブジェクト（unsubscribe() で解除できる）
export function subscribeToTerms(onUpdate) {
  return getConsumer().subscriptions.create(
    // 【購読するチャンネル名】
    //   サーバー側の TermsChannel クラス名と一致させる。
    //
    // 【宛先を送っていないことに注目】
    //   「どのユーザー宛か」をここから送る必要はない。
    //   サーバー側が暗号化されたセッションCookieから判断する。
    //
    //   もしここで user_id を送る設計にすると、
    //   その値を書き換えるだけで他人の通知を受信できてしまう。
    //   クライアントから送られた値で宛先を決めない——
    //   WebSocketで最も多い脆弱性がこれ。
    { channel: 'TermsChannel' },

    {
      // 接続が確立したとき
      connected() {
        console.log('[cable] TermsChannel に接続しました')
      },

      // 切断されたとき
      // 【自動再接続について】
      //   Action Cable は切断を検知すると自動で再接続を試みる。
      //   スマホでアプリを背面に回して戻したときなどに効く。
      //   自前で再接続処理を書く必要はない。
      disconnected() {
        console.log('[cable] TermsChannel から切断されました（自動で再接続します）')
      },

      // サーバーから放送が届いたとき
      received(data) {
        // ジョブ側で { type: 'term_updated', term: {...} } を送っている。
        // 【type で分岐している理由】
        //   将来「タグが更新された」など別の通知を足したときに、
        //   同じチャンネルで種類を見分けられるようにしておく。
        if (data.type === 'term_updated') {
          onUpdate(data.term)
        }
      },
    }
  )
}
