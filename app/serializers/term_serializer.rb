# ============================================================================
# TermSerializer — 単語をJSONの形に変換する
#
# ----------------------------------------------------------------------------
# 【なぜ切り出したのか】
# ----------------------------------------------------------------------------
#   同じ変換処理が2箇所に重複していた。
#
#     TermsController#term_json      … HTTPの応答用
#     ExplainTermJob#broadcast_update … WebSocketの通知用
#
#   カラムを1つ足すたびに両方を直す必要があり、
#   片方だけ直すと「リロードすれば見えるのに、
#   自動更新では反映されない」という切り分けの難しい不具合になる。
#
#   実際フォルダ機能を足す時点で、まさにその危険があった。
#   出力の形は1箇所に集約する。
#
# ----------------------------------------------------------------------------
# 【to_json をそのまま使わない理由】
# ----------------------------------------------------------------------------
#   全カラムが出力されるので、内部用のカラムまで漏れる。
#   さらにカラムを足すたび、意図せずAPIの応答が変わってしまう。
#   出すものを明示的に列挙すれば、そうした事故が起きない。
# ============================================================================
class TermSerializer
  # 【クラスメソッド1つだけにしている理由】
  #   状態を持たない変換処理なので、インスタンスを作る意味が無い。
  #   TermSerializer.call(term) と書けば、それ以上の説明が要らない。
  #
  # @param include_derived [Boolean]
  #   「この解説から掘り下げた語」の一覧を含めるか。
  #
  #   【既定を false にしている理由】← N+1対策
  #     一覧APIで毎回含めると、単語50件それぞれについて
  #     派生語を引くSQLが飛ぶ。
  #     一方この情報が要るのは詳細画面だけなので、
  #     必要な場所から明示的に頼む形にする。
  def self.call(term, include_derived: false)
    {
      id: term.id,
      word: term.word,
      context: term.context,
      meaning: term.meaning,
      examples: term.examples,
      usage_note: term.usage_note,
      status: term.status,          # "pending" / "completed" / "failed"
      error_message: term.error_message,

      # ----------------------------------------------------------------------
      # フォルダ
      # ----------------------------------------------------------------------
      # 【id と name の両方を返す理由】
      #   name だけだと、画面側が「どのフォルダを選択中か」を
      #   名前の文字列比較で判定することになる。
      #   フォルダ名は変更できる仕様なので、変更した瞬間に
      #   選択状態が外れる。識別はIDで行う。
      #
      # 【&. を使う理由】未分類の単語は folder が nil。
      #   nil に .id を呼ぶと落ちる。
      folder_id: term.folder_id,
      folder_name: term.folder&.name,

      # AIが提案した新しいフォルダ名（まだ承認されていない）。
      # 画面はこれが入っているときだけ承認UIを出す。
      suggested_folder_name: term.suggested_folder_name,

      # 【&. を使う理由】generated_at は生成前は nil。
      #   nil に .iso8601 を呼ぶと落ちるので、nil ならそのまま nil を返す。
      generated_at: term.generated_at&.iso8601,

      # 【ISO 8601 形式で返す理由】
      #   "2026-07-19T14:30:00Z" のような国際標準の書き方。
      #   JavaScriptの new Date() がそのまま解釈できる。
      #   "2026/07/19 14:30" のような独自形式だと、
      #   ブラウザや言語によって解釈が変わって事故になる。
      created_at: term.created_at.iso8601,

      tags: term.tags.map { |tag| { id: tag.id, name: tag.name } },

      # ----------------------------------------------------------------------
      # 出自（どの単語の解説を読んでいて調べたか）
      # ----------------------------------------------------------------------
      # 【id と word の両方を返す理由】
      #   word だけだと画面がリンク先を作れない。
      #   id だけだと「CORS から調べた」と表示するために
      #   もう1回APIを叩くことになる。
      source_term_id: term.source_term_id,
      source_term_word: term.source_term&.word,

      # ----------------------------------------------------------------------
      # この解説から掘り下げた語（詳細画面でのみ）
      # ----------------------------------------------------------------------
      # 【include_derived が false のとき空配列を返す理由】
      #   キー自体を消すと、画面側が「まだ読み込んでいない」のか
      #   「1件も無い」のかを区別できず、undefined チェックが増える。
      #   常に配列であることを保証すれば、画面は length を見るだけで済む。
      derived_terms: include_derived ? term.derived_terms.recent.map { |t| { id: t.id, word: t.word } } : []
    }
  end
end
