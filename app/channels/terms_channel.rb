# ============================================================================
# TermsChannel — 単語の更新をブラウザへ配信するチャンネル
#
# 【チャンネルとは】
#   WebSocketの中の「話題」の単位。
#   1本の接続の中で複数の話題を扱えるようにするための仕組み。
#
#   例えば将来「通知」チャンネルを足したくなっても、
#   接続はそのままで、購読する話題を増やすだけで済む。
#
# 【このチャンネルの役割】
#   Sidekiqワーカーが「解説ができた」と放送したものを、
#   そのユーザーのブラウザへ届ける。
# ============================================================================
class TermsChannel < ApplicationCable::Channel
  # --------------------------------------------------------------------------
  # 購読開始時に呼ばれる
  # --------------------------------------------------------------------------
  def subscribed
    # ------------------------------------------------------------------------
    # 【stream_for の意味】
    #   「このユーザー宛の放送を受け取る」という宣言。
    #
    #   ジョブ側の
    #     TermsChannel.broadcast_to(term.user, data)
    #   と対になっている。同じ user を指定した者同士が繋がる。
    #
    # 【なぜ current_user を使うのか — ここが最重要】
    #   もしブラウザから送られてきた値
    #     stream_for User.find(params[:user_id])
    #   を使うと、user_id を書き換えるだけで
    #   他人宛の放送を受信できてしまう。
    #
    #   current_user は Connection が
    #   暗号化されたセッションCookieから確定したもので、
    #   ブラウザ側から偽装できない。
    #
    #   【原則】購読の宛先を、クライアントから送られた値で決めない。
    #   サーバーが知っている事実だけで決める。
    #
    #   これはWebSocketで最も頻出する脆弱性で、
    #   HTTPのAPIでは権限チェックを書いているのに
    #   WebSocketだけ素通し、という実装が実際によくある。
    # ------------------------------------------------------------------------
    stream_for current_user

    Rails.logger.info("[TermsChannel] user_id=#{current_user.id} が購読を開始しました")
  end

  # --------------------------------------------------------------------------
  # 購読終了時に呼ばれる
  # --------------------------------------------------------------------------
  # タブを閉じた・ネットが切れた等で発生する。
  # 【後片付けが不要な理由】
  #   stream_for による購読は、Action Cable が接続の終了時に
  #   自動で解除してくれる。自前で解除する必要はない。
  def unsubscribed
    Rails.logger.info("[TermsChannel] 購読が終了しました")
  end
end
