# ============================================================================
# Llm::ClaudeExplainer — 本番用。実際に Claude API を呼ぶ
#
# 【責務】
#   プロンプト（何を聞くか）と クライアント（どう呼ぶか）を組み合わせ、
#   アプリが扱いやすい形（Explanation）にして返す。
#
#   このクラス自体はHTTPもリトライも知らない。
#   それらは Llm::Client の担当。
#   「組み立てる係」と「実行する係」を分けている。
# ============================================================================
module Llm
  class ClaudeExplainer < Explainer
    # 使うプロンプトを定数で指定する。
    # 【なぜ定数にするか】v2 を作ったとき、
    #   ここ1行を差し替えるだけで切り替えられる。
    #   さらに api_call_logs に記録される prompt_version も
    #   自動的に追随するので、記録と実態がずれない。
    PROMPT = Prompts::ExplainTermV1

    # 【引数で client を受け取れるようにしている理由】
    #   テストで「タイムアウトするクライアント」を差し込みたい場合など、
    #   外から差し替えられる余地を残しておく。
    #   既定値があるので、通常は ClaudeExplainer.new だけで使える。
    def initialize(client: Client.new)
      @client = client
    end

    def call(word:, context: nil)
      # ------------------------------------------------------------------
      # ① プロンプトを組み立てる
      # ------------------------------------------------------------------
      user_message = PROMPT.user_message(word: word, context: context)

      # ------------------------------------------------------------------
      # ② APIを呼ぶ（リトライ・計測は Client の中で行われる）
      # ------------------------------------------------------------------
      parsed, usage = @client.generate_json(
        system: PROMPT::SYSTEM,
        user_message: user_message,
        schema: PROMPT::SCHEMA,
        prompt_version: PROMPT::VERSION
      )

      # ------------------------------------------------------------------
      # ③ アプリ内部の形（値オブジェクト）に変換する
      # ------------------------------------------------------------------
      # 【なぜここで変換するのか】
      #   ここから先のコードが「APIの応答の形」を知らずに済むようにする。
      #   もしAPIの応答のキー名が変わっても、
      #   直すのはこの1行だけで、ジョブやモデルには影響しない。
      #
      #   外部システムとの境界で形を変換する——
      #   この層があるかどうかで、外部の変更に対する強さが変わる。
      [ Explanation.from_api(parsed), usage ]
    end
  end
end
