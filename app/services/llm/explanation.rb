# ============================================================================
# Llm::Explanation — AIが生成した解説を表す値オブジェクト
#
# ----------------------------------------------------------------------------
# 【ファイル名と定数名は一致させること】← ここで一度失敗した箇所
# ----------------------------------------------------------------------------
#   Rails 8 のオートローダ（Zeitwerk）は、
#   「ファイルのパス」から「定義されている定数名」を機械的に決める。
#
#     app/services/llm/explanation.rb  →  Llm::Explanation
#     app/services/llm/client.rb       →  Llm::Client
#
#   最初 llm/result.rb というファイルの中に
#   Llm::Explanation と Llm::Usage の2つを定義していたところ、
#     NameError: uninitialized constant Llm::Client::Usage
#   となった。
#
#   Zeitwerkは result.rb を見て「Llm::Result があるはず」と考えるので、
#   中に別名の定数が入っていても見つけられない。
#
#   【教訓】1ファイル = 1定数。名前も一致させる。
#   Railsが「設定より規約」と言われるのは、こういう規約に従うことで
#   requireを一切書かずに済むようにしているため。
#   規約を外れた瞬間に、その恩恵が失われる。
#
# ----------------------------------------------------------------------------
# 【なぜハッシュではなく専用クラスにするのか】
# ----------------------------------------------------------------------------
#   ハッシュで返すと、呼び出し側は
#     result[:meaning]  … 正しい
#     result[:meanig]   … 打ち間違い → nil が返るだけでエラーにならない
#   となり、間違いに気付けない。
#
#   クラスにしておけば、存在しないメソッドを呼んだ時点で
#   NoMethodError になるので、その場で気付ける。
#
#   また「この処理は何を返すのか」がクラス定義を見れば分かる。
# ============================================================================
module Llm
  # 【Data.define とは】Ruby 3.2 で入った、値オブジェクトを簡潔に作る仕組み。
  #   従来の Struct と似ているが、
  #     ・作った後に変更できない（本当に不変）
  #     ・キーワード引数で作るので、引数の順序を間違えない
  #   という点で、値オブジェクトにはこちらが適している。
  Explanation = Data.define(
    :meaning,        # String … 単語の意味
    :examples,       # Array  … 例文の配列
    :usage_note,     # String … 使い方・使う場面
    :suggested_tags, # Array  … AIが提案したタグ名
    :folder          # String … AIが選んだ／提案したフォルダ名
  ) do
    # ------------------------------------------------------------------------
    # AIの応答（ハッシュ）から作る
    # ------------------------------------------------------------------------
    # 【なぜこの変換層が必要か】
    #   AIの出力をそのまま信じない、という原則のため。
    #   structured output でスキーマを指定していても、
    #   ・examples が文字列で返る
    #   ・キーが欠ける
    #   といった想定外は起こりうる。
    #
    #   ここで一度形を整えておけば、
    #   これ以降のコードは「必ず正しい形」を前提に書ける。
    #   検証の場所を1箇所に集約するのが目的。
    def self.from_api(hash)
      new(
        meaning: hash["meaning"].to_s,
        # 【Array() の意味】nil なら []、配列ならそのまま、
        #   単一の値なら1要素の配列にする。
        #   「配列のはずが文字列だった」場合でも落ちない。
        examples: Array(hash["examples"]).map(&:to_s),
        usage_note: hash["usage_note"].to_s,
        # 【first(5) の理由】AIが大量にタグを返すことがある。
        #   タグが20個付いた単語は分類として意味を成さないので、
        #   上限を設けておく。
        suggested_tags: Array(hash["suggested_tags"]).map(&:to_s).first(5),
        # 【to_s.strip で受ける理由】
        #   キーが欠けていれば nil.to_s = "" になり、
        #   受け取り側は blank? で判定するだけで済む。
        #   nil と "" の両方を気にする必要が無くなる。
        #
        # 【truncate している理由】
        #   folders.name の長さ制限は30文字。
        #   AIが長い名前を返すと検証で落ち、分類だけでなく
        #   解説の保存まで巻き込んで失敗する。
        #   ここで丸めておけば、少なくとも解説は残る。
        folder: hash["folder"].to_s.strip.truncate(30)
      )
    end
  end
end
