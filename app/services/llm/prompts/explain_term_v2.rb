# ============================================================================
# ExplainTermV2 — 単語解説のプロンプトと出力スキーマ
#
# ----------------------------------------------------------------------------
# 【v1 からの変更点】
# ----------------------------------------------------------------------------
#   reading（読み方）と full_form（正式名称・英語表記）の2フィールドを追加した。
#
#   意味が分かっても読めない語がある。「冪等性」を「べきとうせい」と
#   読めなければ会話でも検索でも使えず、結局そこで調べ直すことになる。
#   「調べる手間を消す」という目的に対して、読み方が抜けているのは穴だった。
#
#   【v1 を消さずに残している理由】
#     api_call_logs.prompt_version に記録が残っているので、
#     どのレコードがどの形式で生成されたかを後から判別できる。
#     v1 を書き換えてしまうと、過去のログが指す先が変わり、
#     「このデータには reading があるはず」という誤った前提が生まれる。
#
#   【コストへの影響】
#     追加されるのは出力トークン20個程度（約0.1円未満）。
#     出力は入力の5倍高いため、本文を長くする変更は高くつくが、
#     短い構造化フィールドの追加はほぼ無視できる。
#
# 【なぜプロンプトを独立したファイルにするのか】
#   プロンプトはAIアプリにおける「アルゴリズム」に相当する。
#   出力の品質は、モデルよりもプロンプトで決まる部分が大きい。
#
#   コードの中に文字列として埋め込むと:
#     ・どこにあるか分からなくなる
#     ・変更の履歴が他の変更に埋もれる
#     ・「前の版に戻したい」ができない
#
#   独立させ、さらにファイル名にバージョンを付けておけば、
#   v1 と v2 を並べて比較でき、api_call_logs に記録した
#   prompt_version と突き合わせて効果を測定できる。
#
# 【バージョンを上げるタイミング】
#   出力の形（スキーマ）や方針を変えたとき。
#   誤字修正程度なら上げなくてよい。
#   判断基準は「過去の生成結果と比較したくなるか」。
# ============================================================================
module Llm
  module Prompts
    module ExplainTermV2
      # api_call_logs に記録する識別子。
      VERSION = "explain_term_v2".freeze

      # ======================================================================
      # 出力スキーマ（structured output）
      # ======================================================================
      # 【structured output とは】
      #   「この形のJSONで返せ」とAPI側に強制する仕組み。
      #
      # 【なぜ必須か】
      #   プロンプトで「JSONで答えて」とお願いするだけだと、
      #     ・前後に「はい、承知しました」という文が付く
      #     ・```json ``` で囲まれる
      #     ・キー名が微妙に違う（meaning が definition になる）
      #     ・日本語の引用符が混ざってJSONとして壊れる
      #   といったことが一定の確率で起きる。
      #
      #   1%の失敗でも、100単語登録すれば1回は必ず遭遇する。
      #   その1件のためにパース失敗の処理を書くくらいなら、
      #   最初から形を保証させる方がよい。
      #
      #   スキーマを指定すると、API側が生成の各ステップで
      #   「この形に沿う出力しか作れない」よう制約するため、
      #   構造的に壊れたJSONが返ってこない。
      #
      # 【additionalProperties: false の意味】
      #   ここに書いていないキーを出力させない。
      #   AIが親切心で "note" のような余計なキーを足すのを防ぐ。
      #
      # 【required に全部書く理由】
      #   「あるかもしれないし無いかもしれない」キーがあると、
      #   受け取る側で毎回 nil チェックが必要になる。
      #   全部必須にして、無い場合は空文字を入れさせる方が扱いやすい。
      SCHEMA = {
        type: "object",
        properties: {
          # ------------------------------------------------------------------
          # 読み方
          # ------------------------------------------------------------------
          # 【該当しないときは空文字にさせる理由】
          #   「プリフライト」のように既にカタカナの語には読み方が要らない。
          #   無理に埋めさせると、AIは何かしら書こうとして
          #   不自然な値（"ぷりふらいと" など）を捏造する。
          #   空を許すと明示した方が、正直な出力になる。
          reading: {
            type: "string",
            description: "この単語の読み方をひらがな・カタカナで。" \
                         "例: 「冪等性」→「べきとうせい」、「API」→「エーピーアイ」。" \
                         "既にカタカナで読み方が自明な語（プリフライトなど）は空文字にする。"
          },
          # ------------------------------------------------------------------
          # 正式名称・英語表記
          # ------------------------------------------------------------------
          # 【頭字語の展開と和英を1つにまとめた理由】
          #   利用者から見れば「元の言葉は何か」という同じ問い。
          #   分けると、どちらに入れるべきかAIが迷い、
          #   画面でも2つの空欄を出し分けることになる。
          full_form: {
            type: "string",
            description: "略語なら正式名称を、日本語の用語なら対応する英語表記を返す。" \
                         "例: 「API」→「Application Programming Interface」、" \
                         "「冪等性」→「idempotency」、「CORS」→「Cross-Origin Resource Sharing」。" \
                         "どちらにも当てはまらない語は空文字にする。"
          },
          meaning: {
            type: "string",
            description: "この単語の意味を、専門用語を避けて2〜4文で説明する。" \
                         "比喩を使ってもよい。読み手はWeb開発の新人エンジニア。"
          },
          examples: {
            type: "array",
            description: "具体例。実務で遭遇する場面を想定した短い例を2〜3個。" \
                         "コードが適切な場合はコードを含めてよい。",
            items: { type: "string" }
          },
          usage_note: {
            type: "string",
            description: "どういう場面で使う言葉か、使うときの注意点、" \
                         "混同しやすい別の用語との違いを2〜3文で。"
          },
          suggested_tags: {
            type: "array",
            description: "この単語が属する技術分野を1〜3個。" \
                         "例: Rails, DB, インフラ, セキュリティ, HTTP, 設計。" \
                         "一般的で再利用しやすい粒度にすること。",
            items: { type: "string" }
          },
          # ------------------------------------------------------------------
          # 【タグと別にフォルダを出させる理由】
          #   タグは複数付き細かい。フォルダは1つだけで、辿るための軸。
          #   実測でタグは1単語あたり3個付き、単語30件で40〜50種類に膨らむ。
          #   その粒度ではナビゲーションにならない。
          #
          # 【1つの文字列だけ返させ、既存/新規の判別はサーバー側で行う理由】
          #   「既存から選んだのか、新しく提案したのか」をAIに申告させると、
          #   申告と実態がずれたときに処理が破綻する
          #   （「既存を選んだ」と言いつつ存在しない名前を返す等）。
          #
          #   名前を1つ受け取り、サーバーが既存一覧と突き合わせて判定すれば、
          #   AIの申告を信用する必要がなくなる。
          #   「AIの出力は信用できない入力として扱う」の一例。
          # ------------------------------------------------------------------
          folder: {
            type: "string",
            description: "この単語を入れる場所を1つだけ。" \
                         "ユーザーメッセージに既存フォルダの一覧がある場合、" \
                         "適切なものがあれば、その名前を一字一句そのまま返す。" \
                         "どれにも当てはまらない場合のみ、新しい分類名を提案する。" \
                         "分類名は10〜20件の単語をまとめられる粗さにすること" \
                         "（「HTTPのステータスコード」のような細かすぎる名前は避け、" \
                         "「Web・HTTP」「DB・データ」「設計」程度の粒度にする）。"
          }
        },
        required: [ "reading", "full_form", "meaning", "examples", "usage_note", "suggested_tags", "folder" ],
        additionalProperties: false
      }.freeze

      # ======================================================================
      # システムプロンプト（AIの役割設定）
      # ======================================================================
      # 【システムプロンプトとユーザーメッセージの違い】
      #   システム … 「あなたは誰で、どう振る舞うか」。会話全体で不変
      #   ユーザー … 「今回何をしてほしいか」。毎回変わる
      #
      # 【なぜ分けるのか】
      #   ① 役割が毎回同じなら、prompt caching が効いてコストが下がる
      #      （同じ接頭辞は再計算されず、約1/10の料金で済む）
      #   ② 「役割」と「依頼」が混ざると、AIがどちらを優先すべきか
      #      判断できなくなる
      #
      # 【読み手を具体的に指定している理由】
      #   「分かりやすく説明して」だけでは、AIは基準を持てない。
      #   「新人Webエンジニア向け」と決めれば、
      #   前提として使ってよい語彙の範囲が定まり、出力が安定する。
      SYSTEM = <<~PROMPT.freeze
        あなたはWeb開発の技術用語を教える講師です。読み手は実務1年目のWebエンジニアで、
        HTML/CSS/JavaScript/HTTPの基礎は理解していますが、設計・インフラ・DBの
        専門用語には不慣れです。

        解説するときの方針:

        - 用語を用語で説明しない。「冪等性とはidempotentな性質のこと」のような
          説明は禁止。噛み砕いた日本語で説明する。
        - なぜその概念が必要になったのか、何の問題を解決するのかを含める。
          定義の暗記ではなく、理解につながるようにする。
        - 具体例は抽象的な説明ではなく、実際に遭遇する場面で書く。
          「APIを2回叩いても注文が二重にならない」のような具体性を持たせる。
        - 断定できないことは断定しない。文脈によって意味が変わる用語は、
          その旨を明示する。
        - 冗長にしない。読み手は調べる手間を省きたくてこのアプリを使っている。
      PROMPT

      # ======================================================================
      # ユーザーメッセージの組み立て
      # ======================================================================
      # 【なぜメソッドにするのか】
      #   単語ごとに内容が変わるため。
      #   さらに context（どこで見たか）の有無で文面を変えたい。
      #
      # 【context を渡す価値】
      #   同じ単語でも文脈で意味が変わる。
      #     「セッション」… Web認証の文脈 / DBトランザクションの文脈
      #     「トークン」  … 認証の文脈 / 自然言語処理の文脈
      #   どこで見たかが分かれば、AIは適切な方を選べる。
      # 【folders を渡す理由】
      #   フォルダの分類は「既にどんな置き場所があるか」を知らないとできない。
      #   AIは前回の呼び出しを覚えていないので、毎回一覧を渡す必要がある。
      #
      #   【なぜシステムプロンプト側に入れないのか】
      #   システムプロンプトは会話全体で不変であることを前提に
      #   prompt caching が効く（同じ接頭辞は約1/10の料金）。
      #   フォルダ一覧は単語を登録するたびに変わりうるので、
      #   ここに入れるとキャッシュが毎回無効になり、逆にコストが上がる。
      #   変わるものはユーザーメッセージ側に置く。
      def self.user_message(word:, context: nil, folders: [])
        message = "次の用語を解説してください。\n\n用語: #{word}"

        # 【present? の意味】nilでも空文字でもない、という判定。
        #   Railsが追加しているメソッドで、blank? の逆。
        if context.present?
          message += "\n\nこの用語を見かけた文脈: #{context}"
          message += "\n（この文脈に沿った意味で解説してください）"
        end

        # 【フォルダが0件のときに一覧を書かない理由】
        #   「既存フォルダ: （なし）」と書くと、AIはその文字列自体を
        #   選択肢と誤解して「なし」というフォルダ名を返すことがある。
        #   選ぶ対象が無いなら、そもそも触れない方が誤解が起きない。
        if folders.present?
          message += "\n\n既存のフォルダ一覧:\n"
          message += folders.map { |name| "- #{name}" }.join("\n")
          message += "\n（この中に適切なものがあれば、その名前をそのまま folder に返してください。" \
                     "無い場合のみ新しい分類名を提案してください）"
        end

        message
      end
    end
  end
end
