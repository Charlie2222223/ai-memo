# ============================================================================
# ExplainTermV1 — 単語解説のプロンプトと出力スキーマ
#
# 【なぜプロンプトを独立したファイルにするのか】
#   プロンプトはAIアプリにおける「アルゴリズム」に相当する。
#   出力の品質は、モデルよりもプロンプトで決まる部分が大きい。
#
#   コードの中に文字列として埋め込むと:
#     ・どこにあるか分からなくなる
#     ・変更の履歴が他の変更に埋もれる
#     ・「前の版に戻したい」ができない
#
#   独立させ、さらにファイル名にバージョンを付けておけば、
#   v1 と v2 を並べて比較でき、api_call_logs に記録した
#   prompt_version と突き合わせて効果を測定できる。
#
# 【バージョンを上げるタイミング】
#   出力の形（スキーマ）や方針を変えたとき。
#   誤字修正程度なら上げなくてよい。
#   判断基準は「過去の生成結果と比較したくなるか」。
# ============================================================================
module Llm
  module Prompts
    module ExplainTermV1
      # api_call_logs に記録する識別子。
      VERSION = "explain_term_v1".freeze

      # ======================================================================
      # 出力スキーマ（structured output）
      # ======================================================================
      # 【structured output とは】
      #   「この形のJSONで返せ」とAPI側に強制する仕組み。
      #
      # 【なぜ必須か】
      #   プロンプトで「JSONで答えて」とお願いするだけだと、
      #     ・前後に「はい、承知しました」という文が付く
      #     ・```json ``` で囲まれる
      #     ・キー名が微妙に違う（meaning が definition になる）
      #     ・日本語の引用符が混ざってJSONとして壊れる
      #   といったことが一定の確率で起きる。
      #
      #   1%の失敗でも、100単語登録すれば1回は必ず遭遇する。
      #   その1件のためにパース失敗の処理を書くくらいなら、
      #   最初から形を保証させる方がよい。
      #
      #   スキーマを指定すると、API側が生成の各ステップで
      #   「この形に沿う出力しか作れない」よう制約するため、
      #   構造的に壊れたJSONが返ってこない。
      #
      # 【additionalProperties: false の意味】
      #   ここに書いていないキーを出力させない。
      #   AIが親切心で "note" のような余計なキーを足すのを防ぐ。
      #
      # 【required に全部書く理由】
      #   「あるかもしれないし無いかもしれない」キーがあると、
      #   受け取る側で毎回 nil チェックが必要になる。
      #   全部必須にして、無い場合は空文字を入れさせる方が扱いやすい。
      SCHEMA = {
        type: "object",
        properties: {
          meaning: {
            type: "string",
            description: "この単語の意味を、専門用語を避けて2〜4文で説明する。" \
                         "比喩を使ってもよい。読み手はWeb開発の新人エンジニア。"
          },
          examples: {
            type: "array",
            description: "具体例。実務で遭遇する場面を想定した短い例を2〜3個。" \
                         "コードが適切な場合はコードを含めてよい。",
            items: { type: "string" }
          },
          usage_note: {
            type: "string",
            description: "どういう場面で使う言葉か、使うときの注意点、" \
                         "混同しやすい別の用語との違いを2〜3文で。"
          },
          suggested_tags: {
            type: "array",
            description: "この単語が属する技術分野を1〜3個。" \
                         "例: Rails, DB, インフラ, セキュリティ, HTTP, 設計。" \
                         "一般的で再利用しやすい粒度にすること。",
            items: { type: "string" }
          }
        },
        required: [ "meaning", "examples", "usage_note", "suggested_tags" ],
        additionalProperties: false
      }.freeze

      # ======================================================================
      # システムプロンプト（AIの役割設定）
      # ======================================================================
      # 【システムプロンプトとユーザーメッセージの違い】
      #   システム … 「あなたは誰で、どう振る舞うか」。会話全体で不変
      #   ユーザー … 「今回何をしてほしいか」。毎回変わる
      #
      # 【なぜ分けるのか】
      #   ① 役割が毎回同じなら、prompt caching が効いてコストが下がる
      #      （同じ接頭辞は再計算されず、約1/10の料金で済む）
      #   ② 「役割」と「依頼」が混ざると、AIがどちらを優先すべきか
      #      判断できなくなる
      #
      # 【読み手を具体的に指定している理由】
      #   「分かりやすく説明して」だけでは、AIは基準を持てない。
      #   「新人Webエンジニア向け」と決めれば、
      #   前提として使ってよい語彙の範囲が定まり、出力が安定する。
      SYSTEM = <<~PROMPT.freeze
        あなたはWeb開発の技術用語を教える講師です。読み手は実務1年目のWebエンジニアで、
        HTML/CSS/JavaScript/HTTPの基礎は理解していますが、設計・インフラ・DBの
        専門用語には不慣れです。

        解説するときの方針:

        - 用語を用語で説明しない。「冪等性とはidempotentな性質のこと」のような
          説明は禁止。噛み砕いた日本語で説明する。
        - なぜその概念が必要になったのか、何の問題を解決するのかを含める。
          定義の暗記ではなく、理解につながるようにする。
        - 具体例は抽象的な説明ではなく、実際に遭遇する場面で書く。
          「APIを2回叩いても注文が二重にならない」のような具体性を持たせる。
        - 断定できないことは断定しない。文脈によって意味が変わる用語は、
          その旨を明示する。
        - 冗長にしない。読み手は調べる手間を省きたくてこのアプリを使っている。
      PROMPT

      # ======================================================================
      # ユーザーメッセージの組み立て
      # ======================================================================
      # 【なぜメソッドにするのか】
      #   単語ごとに内容が変わるため。
      #   さらに context（どこで見たか）の有無で文面を変えたい。
      #
      # 【context を渡す価値】
      #   同じ単語でも文脈で意味が変わる。
      #     「セッション」… Web認証の文脈 / DBトランザクションの文脈
      #     「トークン」  … 認証の文脈 / 自然言語処理の文脈
      #   どこで見たかが分かれば、AIは適切な方を選べる。
      def self.user_message(word:, context: nil)
        message = "次の用語を解説してください。\n\n用語: #{word}"

        # 【present? の意味】nilでも空文字でもない、という判定。
        #   Railsが追加しているメソッドで、blank? の逆。
        if context.present?
          message += "\n\nこの用語を見かけた文脈: #{context}"
          message += "\n（この文脈に沿った意味で解説してください）"
        end

        message
      end
    end
  end
end
