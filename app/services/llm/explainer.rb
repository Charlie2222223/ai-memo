# ============================================================================
# Llm::Explainer — 単語解説を生成するもの、の「取り決め」
#
# 【これは何か】
#   実装を持たず、「このメソッドを持っていること」だけを定める。
#   いわゆるインターフェース（抽象基底クラス）。
#
# 【なぜ必要か — 依存関係の逆転】
#   もし ExplainTermJob が ClaudeExplainer を直接呼ぶと、
#   ジョブは「Claudeを呼ぶ」という具体的な事実に縛られる。
#
#   テストのたびに本物のAPIを叩くことになり、
#     ・課金される
#     ・10秒かかる
#     ・返答が毎回違うので結果が安定しない
#     ・「APIが500を返したとき」を再現できない
#   となって、テストが成立しない。
#
#   間にこの取り決めを挟むと、ジョブは
#   「Explainer という約束を守る誰か」に依存する形になる。
#   本番では ClaudeExplainer、テストでは FakeExplainer を
#   差し込めるようになる。
#
#   これを「依存性の注入（DI）」と呼ぶ。
#   Q4で「ハーネスを作りたい」と言ったときの、まさに中心にある考え方。
#
# 【Rubyでのインターフェース】
#   Java等と違い、Rubyには interface 構文が無い。
#   実際には「同じメソッド名を持っていれば動く」（ダックタイピング）。
#
#   それでもこのファイルを作る理由は、
#   「何を実装すればよいか」を人間に伝える文書として機能するため。
#   新しい実装（例: OpenAI版）を足す人が、ここを見れば分かる。
# ============================================================================
module Llm
  class Explainer
    # --------------------------------------------------------------------------
    # 単語の解説を生成する
    #
    # @param word    [String] 解説対象の単語
    # @param context [String, nil] どこで見たかのメモ（任意）
    # @param folders [Array<String>] 既存フォルダ名の一覧。
    #   AIはこの中から選ぶか、どれにも当てはまらなければ新しい名前を提案する。
    #   空配列なら「まだフォルダが無い」＝必ず新規提案になる。
    # @return [Array(Llm::Explanation, Llm::Usage)] 生成結果と計測値
    # @raise [Llm::Client::Error] 生成に失敗した場合
    # --------------------------------------------------------------------------
    def call(word:, context: nil, folders: [])
      # 【NotImplementedError を投げる意味】
      #   このクラスを直接使おうとしたら、その場で気付ける。
      #   継承したのにメソッドを書き忘れた場合も、
      #   実行した瞬間に分かる。
      #
      #   何も書かずに nil を返す実装にすると、
      #   「なぜか解説が空になる」という追いにくい不具合になる。
      raise NotImplementedError, "#{self.class.name} は #call を実装する必要があります"
    end

    # --------------------------------------------------------------------------
    # 現在の環境で使うべき実装を返す
    # --------------------------------------------------------------------------
    # 【なぜここに置くのか】
    #   「どの実装を使うか」の判断を1箇所に集約するため。
    #   呼び出し側（ジョブ）に if Rails.env.test? を書くと、
    #   実装を増やしたときに全ての呼び出し側を直すことになる。
    #
    # 【テスト環境で Fake を返す理由】
    #   rails_helper.rb で外部通信を遮断しているので、
    #   本物を使おうとした時点でテストが落ちる。
    #   ここで切り替えておけば、テストは常に高速・無料・安定して動く。
    def self.build
      if Rails.env.test?
        FakeExplainer.new
      else
        ClaudeExplainer.new
      end
    end
  end
end
