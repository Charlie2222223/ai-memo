# ============================================================================
# Llm::Usage — API呼び出しの計測結果
#
# api_call_logs テーブルに記録する内容と対応する。
#
# 【なぜ Explanation と分けるのか】
#   Explanation は「何が生成されたか」（アプリの関心事）
#   Usage       は「どう生成されたか」（運用の関心事）
#
#   両者は変わる理由が違う。
#   モデルを変えれば Usage の中身は変わるが、Explanation の形は変わらない。
#   変わる理由が違うものは分けておく、が設計の基本。
# ============================================================================
module Llm
  Usage = Data.define(
    :model,
    :prompt_version,
    :input_tokens,
    :output_tokens,
    :latency_ms,
    :attempt
  ) do
    # ------------------------------------------------------------------------
    # 単価表（1トークンあたりのマイクロUSD）
    # ------------------------------------------------------------------------
    # 【マイクロUSDとは】100万分の1ドル。
    #   Claude Opus 4.8 は 100万トークンあたり 入力$5 / 出力$25。
    #   つまり1トークンあたり 入力5マイクロUSD / 出力25マイクロUSD。
    #   ちょうど整数になるので扱いやすい。
    #
    # 【なぜ出力の方が5倍高いのか】
    #   入力は「読む」処理で並列化しやすいが、
    #   出力は1トークンずつ順番に生成するしかないため。
    #   コストを下げたいときは、まず出力を短くするのが効く。
    PRICING = {
      "claude-opus-4-8"  => { input: 5,  output: 25 },
      "claude-sonnet-5"  => { input: 3,  output: 15 },
      "claude-haiku-4-5" => { input: 1,  output: 5 }
    }.freeze

    # ------------------------------------------------------------------------
    # コストをマイクロUSD（整数）で計算する
    # ------------------------------------------------------------------------
    # 【なぜ整数で計算するのか】
    #   小数（float）で金額を扱うと誤差が積み上がる。
    #     0.1 + 0.2 == 0.3   # => false
    #   1件では無視できても、何千件も合計すると金額が合わなくなる。
    #   整数のまま計算し、表示するときだけ割る。
    def cost_micro_usd
      # 【fetch の第2引数】表に無いモデルなら 0 として扱う。
      #   ここで例外にすると、新しいモデルを試した瞬間に
      #   アプリ全体が止まる。
      #   コスト記録の失敗で本体を止めるのは割に合わない。
      price = PRICING.fetch(model, { input: 0, output: 0 })
      (input_tokens * price[:input]) + (output_tokens * price[:output])
    end

    # 人が読める形（ドル）。ログ表示用。
    def cost_usd
      cost_micro_usd / 1_000_000.0
    end
  end
end
