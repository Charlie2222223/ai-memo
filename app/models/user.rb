# ============================================================================
# User モデル — ログインするユーザー
#
# 【モデルとは】
#   DBの1テーブルに対応するRubyのクラス。
#   users テーブルの1行が User オブジェクト1個に対応する。
#
#   ApplicationRecord を継承するだけで、
#     User.find(1) / user.save / user.destroy
#   といったDB操作が全部使えるようになる。SQLを書く必要がない。
#   （この仕組みを ORM = Object-Relational Mapping と呼ぶ）
#
# 【今回このアプリは1人用】
#   ユーザー登録画面は作らない。seed（db/seeds.rb）で自分の
#   アカウントを1件だけ作る。
#   それでも User モデルを作る理由は、
#   「単語が誰のものか」を terms.user_id で表現するため。
#   将来ユーザーが増えても、構造を変えずに済む。
# ============================================================================
class User < ApplicationRecord
  # --------------------------------------------------------------------------
  # パスワード認証の有効化
  # --------------------------------------------------------------------------
  # この1行が裏でやってくれること:
  #
  #   ① password と password_confirmation という「仮想の属性」を追加する
  #      仮想 = DBにカラムは無いが、オブジェクト上では扱える属性。
  #
  #   ② user.password = "秘密" と代入すると、
  #      bcryptで自動的にハッシュ化して password_digest カラムへ入れる。
  #      平文のパスワードはDBに一切保存されない。
  #
  #   ③ user.authenticate("入力値") が使えるようになる。
  #      入力値を同じ手順でハッシュ化し、保存済みの値と一致すれば
  #      そのuser自身を、違えば false を返す。
  #
  #   ④ パスワード必須の検証が自動で入る（新規作成時）。
  #
  # 【なぜハッシュ化は「元に戻せない」方が良いのか】
  #   暗号化なら鍵があれば復号できる。つまり鍵が漏れれば全員のパスワードが漏れる。
  #   ハッシュ化は原理的に戻せないので、DBが丸ごと漏れても
  #   パスワードそのものは分からない。
  #
  #   照合は「入力値を同じ手順で潰して、保存値と一致するか見る」だけでできる。
  #   元に戻す必要がそもそも無いので、戻せない方式を使うのが正しい。
  #
  # 【なぜ bcrypt はわざと遅いのか】← ここが直感に反するポイント
  #   普通のプログラムは速い方が良いが、パスワードのハッシュは逆。
  #
  #   攻撃者はDBを盗んだあと、候補のパスワードを片っ端から試す。
  #   その速度は「1秒間に何回ハッシュ計算できるか」で決まる。
  #
  #     SHA-256（高速なハッシュ）… 1秒に数十億回試せる
  #     bcrypt (コスト12)        … 1秒に数十回しか試せない
  #
  #   1億倍以上の差がつく。正規のログインは1回0.2秒で誰も困らないが、
  #   総当たり攻撃には現実的でない時間がかかるようになる。
  #
  #   「コスト12」は 2^12 = 4096回 計算を繰り返す指定。
  #   PCが速くなったらコストを上げて、攻撃のコストを保ち続けられる設計。
  has_secure_password

  # --------------------------------------------------------------------------
  # メールアドレスの正規化
  # --------------------------------------------------------------------------
  # 【normalizes とは】保存前に値を自動で整える Rails 7.1 以降の機能。
  #
  # 【なぜ必要か】メールアドレスは大文字小文字を区別しない仕様。
  #   "Yazyu@Gmail.com" と "yazyu@gmail.com" は同じ宛先に届く。
  #
  #   しかしDBの文字列比較は大文字小文字を区別するので、
  #   何もしないと両方が別々に登録できてしまい、
  #   ユニーク制約をすり抜ける。
  #
  #   保存前に小文字化・前後の空白除去をしておけば、
  #   DBの中には常に統一された形しか入らない。
  #
  # 【strip も入れている理由】
  #   コピー&ペーストで末尾に空白が混ざるのは非常によくある。
  #   " yazyu@gmail.com" でログインできずに悩む、を防ぐ。
  normalizes :email, with: ->(email) { email.strip.downcase }

  # --------------------------------------------------------------------------
  # 検証（バリデーション）
  # --------------------------------------------------------------------------
  # 【DB制約との役割分担】
  #   マイグレーションにも null: false / unique を書いた。二重に見えるが目的が違う。
  #     モデル側 … 保存前に気付いて、ユーザーに読めるエラーを返す
  #     DB側     … どんな経路でも通さない最後の砦
  #   モデル側だけだと競合状態をすり抜け、DB側だけだと
  #   ユーザーには意味不明なDBエラーが出る。だから両方書く。
  validates :email,
            presence: true,
            # 【format の意味】正規表現に一致するかを検査する。
            #   URI::MailTo::EMAIL_REGEXP はRuby標準のメール形式パターン。
            #   自作の正規表現でメールを検証するのは、仕様が複雑すぎて
            #   ほぼ必ず間違えるので、標準のものを使う。
            format: { with: URI::MailTo::EMAIL_REGEXP, message: "の形式が正しくありません" },
            # 【case_sensitive: false】比較時に大文字小文字を無視する。
            #   normalizes で小文字化しているので実質重複した保険だが、
            #   normalizes を通らない経路（直接 update_column 等）への備え。
            uniqueness: { case_sensitive: false }

  # パスワードの最低文字数。
  # 【allow_nil: true が必要な理由】← 見落としやすい
  #   この検証が常に効くと、パスワードを変えずにメールだけ更新するとき
  #   （user.update(email: ...)）にも password の検証が走ってしまい、
  #   password が nil のせいで保存できなくなる。
  #   allow_nil にしておけば「パスワードを触ったときだけ」検査される。
  #
  # 【なぜ12文字か】一般的には8文字とされることが多いが、
  #   このアプリはインターネットに公開され、APIキーで課金が発生する。
  #   破られたときの損害が金銭に直結するので、長めに設定している。
  validates :password, length: { minimum: 12 }, allow_nil: true

  # --------------------------------------------------------------------------
  # 関連付け（段階3で作る terms との紐付け）
  # --------------------------------------------------------------------------
  # has_many :terms は「1人のユーザーは複数の単語を持つ」という宣言。
  # これを書くと user.terms で、そのユーザーの単語だけを取り出せる。
  #
  # 【dependent: :destroy の意味】
  #   ユーザーを削除したとき、そのユーザーの単語も一緒に削除する。
  #   これが無いと、持ち主が居ない単語（孤児レコード）がDBに残り続ける。
  #
  # 【この1行がセキュリティに効く理由】← 最重要
  #   user.terms.find(params[:id]) と書くと、
  #   発行されるSQLは自動的に
  #     WHERE user_id = 現在のユーザー AND id = 指定されたid
  #   になる。他人のIDを指定しても WHERE で弾かれて見つからない。
  #
  #   一方 Term.find(params[:id]) と書くと user_id の条件が入らないため、
  #   URLの数字を書き換えるだけで他人のデータが見えてしまう。
  #   （これは OWASP が挙げる代表的な脆弱性の一つ）
  #
  #   「常に current_user から辿る」という習慣にしておけば、
  #   権限チェックを書き忘れても構造的に防げる。
  has_many :terms, dependent: :destroy

  # ユーザーが作ったタグ。
  has_many :tags, dependent: :destroy
end
