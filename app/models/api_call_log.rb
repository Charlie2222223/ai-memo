# ============================================================================
# ApiCallLog モデル — Claude API を呼んだ記録
#
# 【このモデルの性格】
#   追記専用（append-only）。一度書いたら書き換えない。
#   「いつ・どのモデルで・何トークン・いくら・成功したか」という
#   起きた事実を記録するだけ。
# ============================================================================
class ApiCallLog < ApplicationRecord
  # optional: true は「関連先が無くてもよい」という指定。
  # 【なぜ必要か】belongs_to は Rails 5 以降、既定で必須になった。
  #   このテーブルは単語が削除されたら term_id が NULL になる設計
  #   （マイグレーションの on_delete: :nullify）なので、
  #   必須のままだと、単語を消した後にログを読むだけで
  #   検証エラーが出るようになってしまう。
  belongs_to :term, optional: true

  # updated_at カラムを作らなかったので、Railsに更新時刻を扱わせない。
  # 【これが無いとどうなるか】
  #   保存時に「updated_at カラムが無い」とエラーになる。
  #   「記録は書き換えない」という設計をコードでも表明している。
  self.record_timestamps = false

  # --------------------------------------------------------------------------
  # 保存前に created_at を入れる
  # --------------------------------------------------------------------------
  # record_timestamps を切ったので、自分で入れる必要がある。
  # 【||= を使う理由】呼び出し側が明示的に時刻を指定した場合は
  #   それを尊重する（テストで時刻を固定したいときなどに効く）。
  before_create { self.created_at ||= Time.current }

  # ==========================================================================
  # スコープ
  # ==========================================================================
  scope :successful, -> { where(success: true) }
  scope :failed,     -> { where(success: false) }

  # 指定した月の記録だけを取り出す。
  # 【引数の既定値 Date.current】呼び出し側が省略したら今月。
  scope :in_month, ->(date = Date.current) {
    where(created_at: date.beginning_of_month..date.end_of_month)
  }

  # ==========================================================================
  # クラスメソッド
  # ==========================================================================

  # --------------------------------------------------------------------------
  # 合計コストをドル単位で返す
  # --------------------------------------------------------------------------
  # 【なぜ最後に割るのか】
  #   マイクロUSD（整数）のまま合計してから、最後に1回だけ割る。
  #   1件ずつドルに直してから足すと、
  #   1件ごとに小数の誤差が出て、件数が増えるほどずれが積み上がる。
  #
  #   「整数のまま計算し、表示するときだけ変換する」——
  #   金額を扱うときの基本形。
  def self.total_cost_usd
    sum(:cost_micro_usd) / 1_000_000.0
  end

  # --------------------------------------------------------------------------
  # 「今月いくら使ったか」を人が読める形で返す
  # --------------------------------------------------------------------------
  # rails console から
  #   ApiCallLog.monthly_summary
  # と打てば現状が分かる。
  #
  # 【なぜこういうメソッドを用意するのか】
  #   必要になるたびにSQLを組み立てるのは面倒で、
  #   面倒だと結局見なくなる。
  #   見るのが簡単だと、実際に見るようになる。
  #   コスト管理は「見る習慣がつくか」が全て。
  def self.monthly_summary(date = Date.current)
    scope = in_month(date)
    {
      月:          date.strftime("%Y-%m"),
      呼び出し回数: scope.count,
      成功:        scope.successful.count,
      失敗:        scope.failed.count,
      入力トークン: scope.sum(:input_tokens),
      出力トークン: scope.sum(:output_tokens),
      合計コストUSD: scope.total_cost_usd.round(4),
      平均所要時間ms: scope.average(:latency_ms)&.round
    }
  end
end
