# ============================================================================
# Term モデル — 1つの単語とその解説
#
# このアプリの中心。
# あなたが word を入れ、AIが meaning / examples / usage_note を埋める。
# ============================================================================
class Term < ApplicationRecord
  # ==========================================================================
  # 関連付け
  # ==========================================================================

  # 持ち主。belongs_to は既定で必須（null を許さない）。
  belongs_to :user

  # --------------------------------------------------------------------------
  # タグとの多対多
  # --------------------------------------------------------------------------
  # 【2行必要な理由】
  #   多対多は中間テーブルを経由するので、
  #   「中間テーブルへの関連」と「その先への関連」の2段階を書く。
  #
  #     has_many :term_tags            … terms → term_tags（1対多）
  #     has_many :tags, through: :term_tags … その先の tags へ繋ぐ
  #
  #   through を書くことで term.tags と直接書けるようになる。
  #   （これが無いと term.term_tags.map(&:tag) と書く羽目になる）
  #
  # 【dependent: :destroy をどちらに付けるか】← 間違えやすい
  #   単語を削除したら、その単語とタグの結び付き（term_tags）は消したい。
  #   しかしタグそのもの（tags）は消してはいけない。
  #   他の単語がまだそのタグを使っているかもしれないからだ。
  #
  #   だから dependent: :destroy は term_tags 側にだけ付ける。
  #   tags 側に付けると、単語を1つ消しただけで
  #   そのタグが他の単語からも消える大事故になる。
  has_many :term_tags, dependent: :destroy
  has_many :tags, through: :term_tags

  # --------------------------------------------------------------------------
  # 所属フォルダ
  # --------------------------------------------------------------------------
  # 【optional: true が必要な理由】
  #   belongs_to は Rails 5 以降、既定で必須（nilを許さない）。
  #   このアプリはフォルダが空の状態から始まる仕様なので、
  #   最初の単語はどこにも所属しない。
  #   optional を書かないと、1件目の登録が検証で落ちる。
  belongs_to :folder, optional: true

  # --------------------------------------------------------------------------
  # 出自（この単語を、どの単語の解説を読んでいて調べたか）
  # --------------------------------------------------------------------------
  # 【自己参照の関連付け】
  #   同じ Term テーブルの別の行を指す。
  #   class_name を書くのは、関連名（source_term）から
  #   Rails が SourceTerm というクラスを探しに行ってしまうため。
  #
  # 【optional: true が必要な理由】
  #   自分で入力欄から登録した単語には出自が無い。
  #   むしろそちらが多数派なので、必須にすると通常の登録が全部落ちる。
  belongs_to :source_term, class_name: "Term", optional: true

  # 【逆向き：この単語の解説から掘り下げた語たち】
  #   foreign_key を明示するのは、Rails が既定で term_id を探すため。
  #   実際のカラムは source_term_id なので教える必要がある。
  #
  # 【dependent: :nullify にする理由】
  #   親を削除したとき、子まで消してはいけない。
  #   1件3.4円かけて生成した解説が、親を消しただけで失われる。
  #   子は「出自不明の単語」として残ればよい。
  #
  #   DB側にも on_delete: :nullify を掛けてある。
  #   Rails を通さない削除でも守られるようにするため。防御は多層で持つ。
  has_many :derived_terms,
           class_name: "Term",
           foreign_key: :source_term_id,
           inverse_of: :source_term,
           dependent: :nullify

  # AI呼び出しの記録。
  # 【dependent を付けない理由】
  #   マイグレーションで on_delete: :nullify を指定したので、
  #   単語が消えると term_id が NULL になり、ログ自体は残る。
  #   コスト集計は単語の存否と無関係に成立すべき記録なので、
  #   Rails側からも消さない。
  has_many :api_call_logs

  # ==========================================================================
  # 状態（enum）
  # ==========================================================================
  # 【enum とは】整数カラムに名前を付けて扱いやすくする仕組み。
  #
  #   DBには 0 / 1 / 2 が入るが、コード上は :pending などで書ける。
  #   さらに次のメソッドが自動生成される:
  #
  #     term.pending?      … 状態を調べる
  #     term.completed!    … 状態を変えて保存する
  #     Term.failed        … 失敗したものだけを取り出すスコープ
  #
  # 【なぜ状態を数値ではなく名前で扱うのか】
  #   status == 2 と書かれたコードは、2が何なのか分からない。
  #   term.failed? なら読んだ瞬間に意味が通る。
  #   DBの容量と可読性を両立させるための仕組み。
  #
  # 【状態遷移の設計】
  #   pending ──成功──> completed
  #      │                  │
  #      └──失敗──> failed ──再生成──> pending（やり直し）
  #
  #   completed から failed へは直接遷移しない。
  #   再生成するときは必ず pending を経由する。
  #   こう決めておくと「今どの段階か」が常に1つに定まる。
  enum :status, { pending: 0, completed: 1, failed: 2 }

  # ==========================================================================
  # 正規化
  # ==========================================================================
  # 前後の空白を取り除く。
  # 【なぜ必要か】コピー&ペーストで空白が混入するのは日常茶飯事。
  #   " 冪等性" と "冪等性" が別レコードとして登録されると、
  #   ユニーク制約をすり抜けて重複が生まれる。
  normalizes :word, with: ->(word) { word.strip }

  # ==========================================================================
  # 検証
  # ==========================================================================
  validates :word,
            presence: true,
            length: { maximum: 100 },
            # 【scope: :user_id の意味】
            #   「同じユーザーの中で」一意、という指定。
            #   これが無いと全ユーザーで単語が重複できなくなる。
            #   マイグレーションの複合ユニークインデックスと対になっている。
            uniqueness: { scope: :user_id, message: "はすでに登録されています" }

  validates :context, length: { maximum: 500 }

  # --------------------------------------------------------------------------
  # フォルダの持ち主が自分と同じか
  # --------------------------------------------------------------------------
  # 【なぜこの検証が必須か】← 権限の穴になりうる箇所
  #   folder_id は利用者が変更できる必要がある（単語を別のフォルダへ移す）。
  #   そのため Strong Parameters で許可せざるを得ない。
  #
  #   しかし許可した以上、他人のフォルダのIDを送りつけられる。
  #   何もしなければ、自分の単語を他人のフォルダに所属させられてしまい、
  #   そのフォルダを開いた他人の画面に自分の単語が現れる。
  #
  #   コントローラ側で毎回チェックする方法もあるが、
  #   経路が増えるたびに書き忘れる。
  #   モデルに置けば、どの経路から保存しても必ず通る。
  #
  #   「権限チェックはif文で書くのではなく、構造的に通らなくする」
  #   という方針（current_user.terms から辿るのと同じ考え方）。
  validate :folder_must_belong_to_same_user

  # --------------------------------------------------------------------------
  # 出自の単語も自分のものか
  # --------------------------------------------------------------------------
  # 【folder_id と同じ穴が開く】
  #   source_term_id は画面から送られてくる値なので、
  #   他人の単語のIDを指定される可能性がある。
  #
  #   通ってしまうと、他人の単語の詳細に
  #   「ここから調べた語」として自分の単語が並ぶ。
  #   相手の画面に自分のデータが現れることになる。
  #
  #   コントローラでチェックする方法もあるが、経路が増えるたびに
  #   書き忘れる。モデルに置けばどの経路からでも必ず通る。
  validate :source_term_must_belong_to_same_user

  # --------------------------------------------------------------------------
  # 自分自身を出自にできない
  # --------------------------------------------------------------------------
  # 【なぜ起こりうるか】
  #   詳細画面のどこを選択してもボタンが出る仕様にしたため、
  #   表示中の単語名そのものを選んで登録しようとすることがある。
  #   （その場合は「既に登録済み」で弾かれるが、
  #     改名して登録すれば自分を指す関係が作れてしまう）
  #
  #   自己参照が入ると「ここから調べた語」に自分が並び、
  #   親を辿ると無限に自分へ戻る表示になる。
  validate :source_term_must_not_be_self

  # ==========================================================================
  # スコープ（よく使う検索条件に名前を付けたもの）
  # ==========================================================================
  # 【スコープとは】
  #   長い検索条件に名前を付けて使い回せるようにする仕組み。
  #   Term.recent と書くだけで「新しい順」が適用される。
  #
  # 【なぜコントローラに直接書かないのか】
  #   同じ条件を複数の場所で使うとき、
  #   1箇所直し忘れて挙動がずれるのを防げる。
  #   また「並び順を変えたい」ときの修正箇所が1つに定まる。
  scope :recent, -> { order(created_at: :desc) }

  # --------------------------------------------------------------------------
  # キーワード検索
  # --------------------------------------------------------------------------
  # 【ILIKE とは】PostgreSQL の「大文字小文字を区別しない LIKE」。
  #   MySQLには無い、PostgreSQL固有の書き方。
  #
  # 【% の意味】任意の文字列にマッチする記号。
  #   "%冪%" なら「冪を含む」という意味になる。
  #
  # 【なぜ ? を使って値を埋め込むのか】← SQLインジェクション対策
  #   もし文字列を直接繋いで
  #     where("word ILIKE '%#{keyword}%'")
  #   と書くと、keyword に
  #     ' OR 1=1 --
  #   のような値を入れられたとき、SQLの構造そのものが書き換わり、
  #   全件が返ったりデータを消されたりする。
  #
  #   ? を使うと、値は「ただの文字列」としてDBに渡され、
  #   SQLの命令として解釈されることが原理的に無くなる。
  #   これをプレースホルダ（バインド変数）と呼ぶ。
  #
  #   【鉄則】ユーザーの入力をSQLに文字列連結で埋め込まない。
  #   例外は無い。
  #
  # 【sanitize_sql_like の役割】
  #   キーワード自体に % や _ が含まれていた場合、
  #   それがワイルドカードとして解釈されてしまうのを防ぐ。
  #   「100%」で検索したときに全件出る、といった挙動を避ける。
  scope :search, ->(keyword) {
    next all if keyword.blank?

    pattern = "%#{sanitize_sql_like(keyword.to_s.strip)}%"
    where("word ILIKE ? OR meaning ILIKE ? OR context ILIKE ?",
          pattern, pattern, pattern)
  }

  # --------------------------------------------------------------------------
  # タグでの絞り込み
  # --------------------------------------------------------------------------
  # 【joins の意味】SQLのJOINを発行して、関連テーブルの条件で絞る。
  #
  # 【distinct が必要な理由】← 多対多で必ず踏む落とし穴
  #   JOINすると、タグを2つ持つ単語は2行として返ってくる。
  #   ┌─────────┬────────┐
  #   │ 冪等性  │ API設計 │  ← 同じ単語が
  #   │ 冪等性  │ インフラ │  ← 2行になる
  #   └─────────┴────────┘
  #   画面に同じ単語が2枚表示されてしまう。
  #   distinct を付けて重複行を潰す。
  #
  #   多対多をJOINしたら distinct、はセットで覚えるとよい。
  scope :with_tag, ->(tag_name) {
    next all if tag_name.blank?

    joins(:tags).where(tags: { name: tag_name }).distinct
  }

  # --------------------------------------------------------------------------
  # フォルダでの絞り込み
  # --------------------------------------------------------------------------
  # 【タグの絞り込みと違い JOIN が要らない理由】
  #   フォルダは1対多なので、terms 側に folder_id を持っている。
  #   JOINも distinct も不要で、単純な WHERE で済む。
  #   多対多（タグ）との実装量の差がそのまま、
  #   「排他的な分類」を選んだ利点になっている。
  #
  # 【"unfiled" という特別な値】
  #   未分類だけを見たい、という要求は必ず出る。
  #   folder_id に nil を渡す方式だと「指定なし（全件）」と
  #   区別が付かないため、専用の文字列で表す。
  scope :in_folder, ->(folder_id) {
    next all if folder_id.blank?
    next where(folder_id: nil) if folder_id.to_s == "unfiled"

    where(folder_id: folder_id)
  }

  # ==========================================================================
  # インスタンスメソッド
  # ==========================================================================

  # --------------------------------------------------------------------------
  # AI生成が成功したときに呼ぶ
  # --------------------------------------------------------------------------
  # 【なぜまとめて1メソッドにするのか】
  #   「本文を入れる」「状態を completed にする」「時刻を記録する」
  #   「エラーを消す」を呼び出し側でバラバラに書くと、
  #   どれか1つを忘れる。
  #
  #   例えば error_message の消し忘れが起きると、
  #   成功しているのに画面にエラーが出続ける。
  #
  #   状態が変わるときに必要な更新は、必ず1箇所にまとめる。
  # 【reading / full_form に既定値を持たせている理由】
  #   このメソッドは再生成でも呼ばれる。v1 で生成された古い単語を
  #   再生成せずに他の経路から更新した場合、引数が渡らないことがある。
  #   既定値 nil を置いておけば、呼び出し側が必ず全部を渡さなくても落ちない。
  def apply_explanation!(meaning:, examples:, usage_note:, reading: nil, full_form: nil)
    update!(
      reading: reading,
      full_form: full_form,
      meaning: meaning,
      examples: examples,
      usage_note: usage_note,
      status: :completed,
      generated_at: Time.current,
      # 【重要】前回の失敗の痕跡を消す。
      #   再生成で成功した場合、古いエラーが残っていると
      #   ユーザーは失敗したままだと誤解する。
      error_message: nil
    )
  end

  # --------------------------------------------------------------------------
  # AI生成が失敗したときに呼ぶ
  # --------------------------------------------------------------------------
  def apply_failure!(message)
    update!(
      status: :failed,
      # 【truncate している理由】
      #   APIの例外メッセージには、応答本文がまるごと入ることがある。
      #   数万文字がDBに入ると、一覧APIの応答が肥大化して
      #   画面が重くなる。原因の判別には冒頭で十分。
      error_message: message.to_s.truncate(500)
    )
  end

  # --------------------------------------------------------------------------
  # 再生成できる状態か
  # --------------------------------------------------------------------------
  # 【なぜ pending を除外するのか】
  #   すでに生成中のものに再生成ボタンを押せると、
  #   同じ単語に対してジョブが2つ走る。
  #   AIを2回呼ぶので課金も2倍になり、
  #   どちらの結果が最終的に残るかも不定になる。
  def regeneratable?
    completed? || failed?
  end

  # --------------------------------------------------------------------------
  # AIの分類結果を反映する
  # --------------------------------------------------------------------------
  # 【2つに分岐する理由】
  #   既存のフォルダに当てはまるなら黙って入れる。
  #   当てはまらないなら「提案」として置くだけで、勝手にフォルダを作らない。
  #
  #   勝手に作ると、フォルダが際限なく増えてタグと同じ末路をたどる。
  #   フォルダの価値は「少なくて安定していること」なので、
  #   増やす判断は必ず人間が行う。
  #
  # 【まとめて1メソッドにする理由】
  #   apply_explanation! と同じ。呼び出し側で
  #   「folder を入れる」「suggested を消す」を別々に書くと必ず片方を忘れ、
  #   確定済みなのに提案が残り続ける、といった状態が生まれる。
  def apply_folder_suggestion!(name)
    return if name.blank?

    existing = Folder.find_by_name_for(user, name)

    if existing
      # 既存に当てはまった → 確定。提案は残さない
      update!(folder: existing, suggested_folder_name: nil)
    else
      # 当てはまらない → 提案として保持。所属は未分類のまま
      update!(suggested_folder_name: name.to_s.strip)
    end
  end

  # --------------------------------------------------------------------------
  # AIの提案を承認して、実際にフォルダを作る
  # --------------------------------------------------------------------------
  # 【トランザクションで囲む理由】
  #   フォルダの作成と、単語の所属変更は必ずセットで成立させたい。
  #   途中で失敗すると「フォルダはできたが空のまま、
  #   単語は未分類で提案も消えた」という宙ぶらりんの状態が残る。
  def accept_suggested_folder!
    return if suggested_folder_name.blank?

    transaction do
      folder = Folder.find_or_create_for(user, suggested_folder_name)
      update!(folder: folder, suggested_folder_name: nil)
    end
  end

  private

  def folder_must_belong_to_same_user
    return if folder.nil?
    return if folder.user_id == user_id

    # 【メッセージを具体的にしない理由】
    #   「そのフォルダは他人のものです」と返すと、
    #   指定したIDが実在することを教えてしまう。
    #   他人のリソースに404を返すのと同じ考え方。
    errors.add(:folder, "が正しくありません")
  end

  def source_term_must_belong_to_same_user
    return if source_term.nil?
    return if source_term.user_id == user_id

    # フォルダと同じ理由で、他人のものだと明かさない書き方にする。
    errors.add(:source_term, "が正しくありません")
  end

  def source_term_must_not_be_self
    # 【persisted? で囲む理由】
    #   新規作成時は id がまだ nil。
    #   nil == nil が成立してしまい、出自を指定していない
    #   通常の登録まで弾かれる。
    return if id.nil? || source_term_id.nil?
    return if source_term_id != id

    errors.add(:source_term, "に自分自身は指定できません")
  end
end
