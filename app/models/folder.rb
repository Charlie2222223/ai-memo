# ============================================================================
# Folder モデル — 単語の置き場所
#
# 【タグとの違い】
#   タグ    … 1単語に複数付く。細かく重なり合う。検索の手掛かり
#   フォルダ … 1単語に1つだけ。少数で安定。辿るための軸
#
#   詳しい経緯は db/migrate/*_create_folders.rb のコメントを参照。
# ============================================================================
class Folder < ApplicationRecord
  belongs_to :user

  # --------------------------------------------------------------------------
  # 【dependent: :nullify を選ぶ理由】← 向きを間違えると単語が消える
  # --------------------------------------------------------------------------
  #   フォルダを削除したとき、中の単語をどうするか。
  #
  #     :destroy … 単語ごと消える。絶対に選んではいけない
  #     :nullify … 単語は残り、未分類に戻る ← これ
  #
  #   利用者の意図は「この分類をやめたい」であって
  #   「この単語たちを捨てたい」ではない。
  #   1件3.4円かけて生成した解説を、整理の巻き添えで失わせない。
  #
  #   DB側にも on_delete: :nullify を掛けてある。
  #   Rails を通さない削除（rails db での直接操作など）でも
  #   単語が守られるようにするため。防御は多層で持つ。
  has_many :terms, dependent: :nullify

  # --------------------------------------------------------------------------
  # 名前の正規化
  # --------------------------------------------------------------------------
  # 【小文字化しない理由】Tag と同じ。
  #   "Web・HTTP" を "web・http" にすると表示に違和感が出る。
  #   「表示は入力どおり、比較は小文字で」という方針。
  normalizes :name, with: ->(name) { name.strip }

  validates :name,
            presence: true,
            length: { maximum: 30 },
            uniqueness: { scope: :user_id, case_sensitive: false }

  # 表示順。
  # 【名前順にする理由】作成順だと、AIが提案を承認するたびに
  #   末尾に積まれて、探すときの位置が毎回変わる。
  #   名前順なら位置が安定し、「いつもここにある」という記憶が効く。
  scope :alphabetical, -> { order(:name) }

  # --------------------------------------------------------------------------
  # 名前からフォルダを引く（無ければ作る）
  # --------------------------------------------------------------------------
  # 【大文字小文字を無視して探す理由】
  #   AIは "Web・HTTP" と "web・HTTP" のような揺れを返す。
  #   小文字で比較して既存を見つけられれば、
  #   表記揺れによる重複フォルダの乱立を防げる。
  #
  # 【LOWER(name) = LOWER(?) という書き方】
  #   PostgreSQLで大文字小文字を無視した比較をする。
  #   この書き方は name カラムの索引を使えなくするが、
  #   フォルダは多くても数十件なので問題にならない。
  #   （Tag に同じ書き方があり、理由も同じ）
  def self.find_or_create_for(user, name)
    normalized = name.to_s.strip
    return nil if normalized.blank?

    find_by_name_for(user, normalized) || user.folders.create!(name: normalized)
  end

  # --------------------------------------------------------------------------
  # 名前からフォルダを探す（作らない）
  # --------------------------------------------------------------------------
  # 【find_or_create_for と分けている理由】
  #   AIの分類では「既にあるなら入れる、無いなら提案に留める」という
  #   判断が要る。作ってしまう版しか無いと、この判断ができない。
  def self.find_by_name_for(user, name)
    normalized = name.to_s.strip
    return nil if normalized.blank?

    user.folders.where("LOWER(name) = LOWER(?)", normalized).first
  end
end
