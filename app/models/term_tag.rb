# ============================================================================
# TermTag モデル — 単語とタグを結ぶ中間テーブル
#
# 【中身がほとんど無いのは正常】
#   中間テーブルの役割は「AとBが結び付いている」という事実の記録だけ。
#   固有の振る舞いを持たないので、モデルも小さくなる。
#
# 【それでもファイルを作る理由】
#   Railsには has_and_belongs_to_many という、
#   中間テーブルのモデルを作らずに多対多を表す書き方もある。
#   しかし実務では、こちらの has_many :through を使うのが定石。
#
#   理由は「後から中間テーブルに情報を足したくなる」から。
#     ・いつタグが付いたか（created_at）
#     ・誰が付けたか（人が付けたのか、AIが付けたのか）
#     ・確度はどれくらいか（AIの提案の確からしさ）
#
#   habtm を選ぶとこれらを足すときに作り直しになる。
#   最初から through にしておけば、カラムを足すだけで済む。
# ============================================================================
class TermTag < ApplicationRecord
  belongs_to :term
  belongs_to :tag

  # --------------------------------------------------------------------------
  # 同じ組み合わせを2回作らせない
  # --------------------------------------------------------------------------
  # 【DB側の複合ユニークインデックスと二重で守る】
  #   モデル側 … 保存前に気付いて、扱いやすいエラーを返す
  #   DB側     … 同時実行をすり抜けさせない最後の砦
  #
  #   users.email のときと同じ考え方。
  validates :tag_id, uniqueness: { scope: :term_id }
end
