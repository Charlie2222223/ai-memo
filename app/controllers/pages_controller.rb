# ============================================================================
# PagesController — SPA（Vue）の入口となるHTMLを1枚返すだけのコントローラ
#
# 【SPA（Single Page Application）の仕組み】
#   従来のWebアプリは、ページを移動するたびにサーバーへ行き、
#   サーバーが毎回HTMLを組み立てて返していた（画面が白くなって再読み込み）。
#
#   SPAは違う。最初の1回だけHTMLを受け取り、以降の画面切り替えは
#   ブラウザの中でJavaScriptがやる。サーバーとはデータ（JSON）だけを
#   やり取りする。画面が再読み込みされないので、切り替えが速く滑らか。
#
#   このアプリでの役割分担:
#     PagesController  … 最初の1枚のHTMLを返す（これだけ）
#     Vue Router       … 以降の画面切り替えを担当
#     TermsController  … データ（JSON）を返す
#
# 【なぜ「1枚だけ」で足りるのか】
#   /（一覧）でも /terms/5（詳細）でも、返すHTMLは同じ。
#   URLを見て何を表示するかは、Vue側が判断する。
#   だからサーバー側は「どのURLでも同じHTMLを返す」だけでよい。
# ============================================================================
class PagesController < ApplicationController
  # --------------------------------------------------------------------------
  # 入口のHTMLは未ログインでも返す
  # --------------------------------------------------------------------------
  # 【なぜ認証を外すのか】
  #   ログインしていない人にもログイン画面は見せる必要がある。
  #   そしてそのログイン画面自体がVueで作られているので、
  #   Vueを起動するためのHTMLは誰でも取得できないといけない。
  #
  # 【中身が漏れないのはなぜか】
  #   このHTMLには単語データは一切含まれていない。
  #   空の器とJavaScriptだけ。
  #   実際のデータは /api/terms から取得するが、そちらは
  #   認証必須なので、未ログインでは 401 が返って何も表示できない。
  #
  #   「画面の枠は誰でも取れるが、中身は認証がないと取れない」
  #   という構造。SPAでは一般的な形。
  skip_before_action :require_authentication

  def index
    # 明示的に何も書かなくても、Railsの規約により
    # app/views/pages/index.html.erb が描画される。
    #
    # 【あえて空のメソッドを書く理由】
    #   メソッド自体を消してもRailsは動く（テンプレートがあれば描画される）が、
    #   コードを読んだ人が「このアクションは存在するのか？」と
    #   迷わずに済むよう、明示しておく。
  end
end
