# ============================================================================
# TagsController — タグ一覧（絞り込みUI用）
#
# 作成・更新・削除が無いのは、タグが単語の登録時に
# 自動で作られる設計だから（AIが提案したタグをその場で作る）。
# 必要な機能だけを公開する、が原則。
# ============================================================================
class TagsController < ApplicationController
  # ==========================================================================
  # GET /api/tags — 自分のタグ一覧
  # ==========================================================================
  def index
    # ------------------------------------------------------------------------
    # 【なぜ単純な current_user.tags ではないのか】
    #   絞り込みUIには「そのタグが何件に付いているか」を出したい。
    #     [Rails 12] [インフラ 8] [DB 3]
    #   件数が分かると、使われていないタグに気付ける。
    #
    # 【left_joins を使う理由】← joins との違いが重要
    #   joins（内部結合）は「結び付きがある行だけ」を返す。
    #   → まだ1件も単語が付いていないタグが一覧から消える。
    #
    #   left_joins（外部結合）は「結び付きが無くても左側は残す」。
    #   → 件数0のタグもちゃんと表示される。
    #
    #   「片方が空でも残したいかどうか」で使い分ける。
    #
    # 【group + count の組み合わせ】
    #   SQLの GROUP BY にあたる。タグごとに行をまとめて数える。
    #   これを書かずにRuby側で
    #     tags.map { |t| t.terms.count }
    #   と書くと、タグの数だけSQLが飛ぶ（N+1問題）。
    #   1本のSQLで済ませる方が圧倒的に速い。
    # ------------------------------------------------------------------------
    tags = current_user.tags
                       .left_joins(:term_tags)
                       .group(:id)
                       .order(:name)
                       # 【count("term_tags.id") と書く理由】
                       #   単に count とすると、外部結合で生じた
                       #   NULL の行まで1件として数えてしまい、
                       #   単語が0件のタグが「1件」と表示される。
                       #   特定の列を数えれば NULL は除外される。
                       .count("term_tags.id")

    # 【count の戻り値の形】
    #   group を付けた count は { タグID => 件数 } のハッシュを返す。
    #   タグ名を出すには、別途タグ本体を引いて突き合わせる必要がある。
    tag_records = current_user.tags.where(id: tags.keys).index_by(&:id)

    render json: {
      tags: tags.map { |tag_id, count|
        {
          id: tag_id,
          name: tag_records[tag_id].name,
          terms_count: count
        }
      }.sort_by { |t| t[:name] }
    }
  end
end
