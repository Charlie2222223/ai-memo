# ============================================================================
# SessionsController — ログイン・ログアウトを担当
#
# 【なぜ「Sessions」という名前なのか】← Railsの考え方
#   直感的には LoginController と名付けたくなるが、Railsでは
#   「操作」ではなく「資源（リソース）」に名前を付ける規約がある。
#
#   ログインとは何をしているのか、を突き詰めると
#   「セッションという資源を作る（create）／壊す（destroy）」こと。
#
#     ログイン  = セッションを作る   → POST   /api/session
#     ログアウト = セッションを壊す   → DELETE /api/session
#     ログイン確認 = セッションを見る → GET    /api/session
#
#   こう捉えると、単語の登録・削除とまったく同じ形になる。
#   資源ごとに create / show / destroy が並ぶので、
#   コントローラを開けば何ができるか即座に分かる。これがRESTという考え方。
# ============================================================================
class SessionsController < ApplicationController
  # --------------------------------------------------------------------------
  # ログイン系はログイン不要（当然だが、明示が必要）
  # --------------------------------------------------------------------------
  # ApplicationController で全体に require_authentication を掛けたので、
  # そのままだと「ログインするにはログインが必要」という
  # 入れない状態になる。ここだけ明示的に外す。
  #
  # 【only: で絞る理由】destroy（ログアウト）まで外す必要はない。
  #   ログインしていない人がログアウトすることは無いので、
  #   認証を掛けたままで問題ない。
  #   外す範囲は最小限にする、が原則。
  skip_before_action :require_authentication, only: [ :create, :show ]

  # --------------------------------------------------------------------------
  # GET /api/session — 今ログインしているか確認する
  # --------------------------------------------------------------------------
  # 【何のためにあるか】
  #   Vue（SPA）はページを開いた瞬間、自分がログイン済みか判断できない。
  #   セッションCookieは httpOnly なのでJavaScriptからは読めないからだ。
  #
  #   そこで起動時にこのエンドポイントを1回叩き、
  #   「ログイン済みならユーザー情報、未ログインなら null」を受け取って
  #   ログイン画面を出すか単語一覧を出すかを決める。
  def show
    if user_signed_in?
      render json: { user: user_json(current_user) }
    else
      # 【なぜ 401 ではなく 200 + null なのか】← 意図的な使い分け
      #   「ログインしているか確認する」に対して「していない」は
      #   エラーではなく正常な答え。
      #   401 を返すとブラウザのコンソールが赤くなり、
      #   本物の異常と見分けがつかなくなる。
      #   問い合わせ自体は成功しているので 200 が適切。
      render json: { user: nil }
    end
  end

  # --------------------------------------------------------------------------
  # POST /api/session — ログイン
  # --------------------------------------------------------------------------
  def create
    # 【&. （ぼっち演算子）の意味】
    #   user が nil のときに user.authenticate を呼ぶと
    #   NoMethodError で落ちる。&. は「左が nil なら nil を返して呼ばない」。
    #
    #   つまりこの1行は
    #     ・そのメールのユーザーが存在しない → nil（＝失敗）
    #     ・存在するがパスワードが違う      → false（＝失敗）
    #     ・存在してパスワードも合う        → user オブジェクト
    #   を1行で表現している。
    user = User.find_by(email: params[:email].to_s.strip.downcase)

    if user&.authenticate(params[:password].to_s)
      # 認証成功。Authentication モジュールの sign_in を呼ぶ。
      # 中で reset_session を実行し、セッション固定攻撃を防いでいる。
      sign_in(user)
      render json: { user: user_json(user) }, status: :ok
    else
      # ------------------------------------------------------------------
      # 【エラーメッセージをわざと曖昧にしている】← セキュリティ上の判断
      #
      #   「メールアドレスが存在しません」と親切に返すと、
      #   攻撃者はメールアドレスを次々送って
      #   「どのアドレスが登録済みか」を調べられてしまう（列挙攻撃）。
      #   登録済みと分かれば、そのアドレスに絞って
      #   パスワードの総当たりやフィッシングを仕掛けられる。
      #
      #   どちらが間違っていても同じ文言にすることで、
      #   アドレスの存在有無を漏らさない。
      #
      #   親切さとセキュリティが正面から対立する場面で、
      #   ログイン画面ではセキュリティを優先するのが定石。
      # ------------------------------------------------------------------
      render json: { error: "メールアドレスまたはパスワードが違います" },
             status: :unauthorized
    end
  end

  # --------------------------------------------------------------------------
  # DELETE /api/session — ログアウト
  # --------------------------------------------------------------------------
  def destroy
    sign_out
    # 【head :no_content の意味】本文を持たない 204 応答を返す。
    #   ログアウトは「消えた」という事実だけが結果で、
    #   返すべきデータが無い。空のJSONを返すより意図が明確。
    head :no_content
  end

  private

  # --------------------------------------------------------------------------
  # ユーザー情報をJSONに変換する
  # --------------------------------------------------------------------------
  # 【なぜ user.to_json をそのまま使わないのか】← 事故防止
  #   to_json は既定で全カラムを出力する。つまり
  #   password_digest まで応答に含まれてしまう。
  #
  #   ハッシュ値なので即座に悪用はされないが、
  #   オフラインで総当たりを試す材料を自分から渡すことになる。
  #
  #   さらに危険なのは将来の変更で、
  #   後から「電話番号」「住所」のようなカラムを足したとき、
  #   全カラム出力だと自動的にAPIから漏れ出す。
  #
  #   「出したいものだけを明示的に書く」形にしておけば、
  #   カラムが増えても勝手に漏れることはない。
  #   これを「許可リスト方式」と呼び、セキュリティ設計の基本原則。
  def user_json(user)
    { id: user.id, email: user.email }
  end
end
