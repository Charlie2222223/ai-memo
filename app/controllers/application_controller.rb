# ============================================================================
# ApplicationController — 全コントローラの親クラス
#
# このアプリの全コントローラはこれを継承する。
# ここに書いた設定は、アプリ全体に効く。
# ============================================================================
class ApplicationController < ActionController::Base
  # --------------------------------------------------------------------------
  # 認証機能の取り込み
  # --------------------------------------------------------------------------
  # app/controllers/concerns/authentication.rb で定義したモジュールを取り込む。
  # これで current_user / sign_in / require_authentication などが使えるようになる。
  include Authentication

  # --------------------------------------------------------------------------
  # 既定でログインを必須にする（セキュアバイデフォルト）
  # --------------------------------------------------------------------------
  # 【なぜ「全体に掛けてから個別に外す」のか】← 設計の要
  #   逆向き（必要なコントローラにだけ認証を書く）にすると、
  #   新しいコントローラを追加したとき書き忘れた場所が
  #   そのまま誰でも見られる状態になる。
  #
  #   ・書き忘れ → 公開されてしまう（危険側に倒れる）
  #   ・書き忘れ → ログインが必要になる（安全側に倒れる）  ← こちらを選ぶ
  #
  #   人間は必ず書き忘れるので、書き忘れたときに
  #   どちらへ倒れるかで設計を決める。
  #
  #   ログイン画面など認証が不要な場所では、そのコントローラで
  #     skip_before_action :require_authentication
  #   と書いて明示的に外す。「外した」という事実がコードに残るのが利点。
  before_action :require_authentication

  # --------------------------------------------------------------------------
  # ブラウザのバージョン制限（Railsが生成した既定の設定）
  # --------------------------------------------------------------------------
  # 古すぎるブラウザを弾く。今どきのCSS/JSが動かない環境を
  # 相手にしないことで、動作確認の手間を減らす狙い。
  allow_browser versions: :modern

  # --------------------------------------------------------------------------
  # CSRF（クロスサイトリクエストフォージェリ）対策
  # --------------------------------------------------------------------------
  # 【CSRFとは】← Cookie認証を使う以上、必ず対策が要る攻撃
  #
  #   ブラウザは「そのドメイン宛のリクエストには自動でCookieを付ける」。
  #   便利な反面、これを悪用できてしまう。
  #
  #   攻撃の流れ:
  #     ① あなたが memo.fly.dev にログイン済み（Cookieを持っている）
  #     ② 別タブで攻撃者のサイト evil.example を開く
  #     ③ そのページに、こっそりこんなHTMLが仕込まれている:
  #          <form action="https://memo.fly.dev/api/terms/1" method="post">
  #            <input name="_method" value="delete">
  #          </form>
  #          <script>document.forms[0].submit()</script>
  #     ④ ブラウザは memo.fly.dev 宛なのでCookieを自動で付けて送信
  #     ⑤ サーバーから見ると「本人の正規のリクエスト」に見える
  #        → あなたの単語が勝手に削除される
  #
  #   ポイントは「攻撃者はCookieの中身を読めないが、送らせることはできる」こと。
  #
  # 【対策の仕組み】
  #   サーバーが発行した予測不能なトークンを、リクエストに含めさせる。
  #   このトークンはページのHTML内（meta タグ）に埋め込まれる。
  #   攻撃者は別ドメインなので、同一オリジンポリシーにより
  #   memo.fly.dev のHTMLを読めない → トークンを知りようがない。
  #   → トークンの無いリクエストは弾かれる。
  #
  # 【with: :exception の意味】
  #   トークンが不正なら例外を投げて処理を止める。
  #   もう一つの選択肢 :null_session は「セッションを空にして処理は続行」だが、
  #   気付きにくい挙動になるので、明確に失敗させる :exception を選ぶ。
  protect_from_forgery with: :exception

  # --------------------------------------------------------------------------
  # 見つからなかったときの応答
  # --------------------------------------------------------------------------
  # 【rescue_from とは】指定した例外が起きたとき、
  #   エラー画面を出す代わりに自前の処理を呼ぶ仕組み。
  #
  # 【なぜ「他人のデータ」に 403 ではなく 404 を返すのか】← 設計判断
  #   user.terms.find(999) は、他人の単語だと RecordNotFound になる。
  #   これを 404（存在しない）として返す。
  #
  #   403（権限が無い）を返すと、攻撃者に
  #   「このIDは存在する。ただし自分のものではない」という情報を与えてしまう。
  #   IDを順に試せば「どのIDが使われているか」の地図が作れる。
  #
  #   404 で統一すれば「存在しないのか、自分のものでないのか」を
  #   区別できず、情報が漏れない。
  #   これを「列挙攻撃（enumeration）への対策」と呼ぶ。
  rescue_from ActiveRecord::RecordNotFound, with: :render_not_found

  private

  def render_not_found
    respond_to do |format|
      format.json { render json: { error: "見つかりません" }, status: :not_found }
      format.html { render "pages/index", status: :not_found }
    end
  end
end
