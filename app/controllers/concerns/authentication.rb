# ============================================================================
# Authentication — 「今ログインしているのは誰か」を扱う共通処理
#
# 【Concern とは】
#   複数のクラスで使い回したいメソッド群をまとめた部品。
#   Rubyの module（モジュール）という仕組みを使っている。
#
#   継承（class A < B）は1つの親しか持てないが、
#   モジュールは何個でも取り込める。
#   「機能を横から足す」ときに使うのがモジュール。
#
# 【なぜApplicationControllerに直接書かないのか】
#   認証・権限・ログ出力…と全部を1ファイルに書くと数百行になり、
#   どこに何があるか分からなくなる。
#   「認証まわりはこのファイル」と決めておけば、
#   認証の挙動を知りたいときに読む場所が1つに定まる。
# ============================================================================
module Authentication
  # ActiveSupport::Concern を extend すると、
  # included do ... end や class_methods do ... end という
  # 読みやすい書き方が使えるようになる。
  extend ActiveSupport::Concern

  # included do ... end の中身は、
  # このモジュールを取り込んだクラス側で実行される。
  # つまり ApplicationController に直接書いたのと同じ効果になる。
  included do
    # ------------------------------------------------------------------------
    # ビュー（HTML）からも current_user を使えるようにする
    # ------------------------------------------------------------------------
    # helper_method を書かないと、これらのメソッドはコントローラの中でしか
    # 呼べない。ビューで「ログイン中ならログアウトボタンを出す」といった
    # 出し分けをしたいので、ビューからも見えるようにしておく。
    helper_method :current_user, :user_signed_in?
  end

  private

  # --------------------------------------------------------------------------
  # 今ログインしているユーザーを返す（居なければ nil）
  # --------------------------------------------------------------------------
  def current_user
    # 【この書き方（メモ化）の意味】
    #   @current_user ||= ... は
    #   「@current_user がまだ入っていなければ右辺を実行して代入、
    #     すでに入っていればそれをそのまま返す」という意味。
    #
    # 【なぜ必要か】1回のリクエスト処理の中で current_user は
    #   何度も呼ばれる（権限チェックで1回、ビューで1回、ログで1回…）。
    #   毎回DBに問い合わせると、同じSELECTが何度も走って無駄。
    #   1回目の結果を覚えておけば、2回目以降はDBに行かない。
    #
    #   なお @変数 はリクエストごとに作り直されるので、
    #   別のユーザーのリクエストに値が漏れることはない。
    @current_user ||= authenticate_user_from_session
  end

  # --------------------------------------------------------------------------
  # ログインしているかどうかの真偽値
  # --------------------------------------------------------------------------
  # 【末尾の ? について】Rubyの慣習で「真偽値を返すメソッド」に付ける。
  #   文法上の強制ではないが、付いていれば読み手は
  #   「これはtrue/falseが返る」と即座に分かる。
  #
  # 【.present? の意味】nilや空でなければtrue。
  #   current_user は「居なければnil」なので、これで判定できる。
  def user_signed_in?
    current_user.present?
  end

  # --------------------------------------------------------------------------
  # セッションからユーザーを復元する
  # --------------------------------------------------------------------------
  # 【セッションとは】
  #   HTTPは「ステートレス」——1回のやり取りが終わると、サーバーは
  #   相手が誰だったかを完全に忘れる。次のリクエストは赤の他人として届く。
  #
  #   これでは毎回ログインし直すことになるので、
  #   「あなたは番号◯番の客です」という札（Cookie）をブラウザに渡し、
  #   サーバー側は番号と中身の対応表（セッション）を持っておく。
  #
  #   session[:user_id] に入れた値は、
  #   Railsが暗号化・署名してCookieに書き込む。
  #   次のリクエストでブラウザがそのCookieを送ってくるので、
  #   Railsが復号して session[:user_id] として読み出せる。
  #
  # 【なぜCookieの中身を書き換えられないのか】
  #   Railsはセッション内容に「署名」を付ける。
  #   署名の鍵はサーバーだけが持っている（config/master.key）。
  #   ユーザーがCookieの中身を user_id=999 に書き換えても、
  #   署名が合わなくなるのでRailsは丸ごと無効として捨てる。
  #   → 「他人になりすます」ことができない。
  def authenticate_user_from_session
    # session[:user_id] が nil のときは User.find_by(id: nil) となり、
    # 素直に nil が返る（例外にならない）。
    #
    # 【find ではなく find_by を使う理由】
    #   find は見つからないと例外（RecordNotFound）を投げる。
    #   find_by は nil を返す。
    #   ここでは「ログインしていない」は正常な状態であって
    #   異常ではないので、例外ではなく nil が適切。
    #
    # 【なぜ「セッションにIDだけ」入れて毎回DBを引くのか】
    #   ユーザー情報そのものをCookieに入れると、
    #   ・メールアドレスを変えても古い値が残り続ける
    #   ・アカウントを削除しても、そのCookieを持つ人は使い続けられる
    #   という問題が出る。IDだけ入れて毎回DBから引けば、常に最新かつ、
    #   DBから消せば即座に無効化できる。
    User.find_by(id: session[:user_id])
  end

  # --------------------------------------------------------------------------
  # ログイン必須にする（before_action から呼ぶ）
  # --------------------------------------------------------------------------
  # 【使い方】コントローラに
  #     before_action :require_authentication
  #   と書くと、そのコントローラの全アクションの実行前にこれが走る。
  #
  # 【なぜ「必須にする」側を明示するのか】← 設計の考え方
  #   逆に「ログイン不要なページにだけ印を付ける」設計にすると、
  #   新しくコントローラを足したとき、印を付け忘れた場所が
  #   誰でも見られる状態になってしまう。
  #
  #   ApplicationController で全体に require_authentication をかけ、
  #   公開したいページだけ skip_before_action で外す形にすれば、
  #   「書き忘れ = 公開されてしまう」ではなく
  #   「書き忘れ = ログインが必要になる（安全側）」になる。
  #   これを「セキュアバイデフォルト（既定で安全）」と呼ぶ。
  def require_authentication
    return if user_signed_in?

    # ------------------------------------------------------------------------
    # 未ログインのときの応答
    # ------------------------------------------------------------------------
    # 【401 Unauthorized】「あなたが誰か分からない」＝ログインしてください。
    #   （紛らわしいが 403 Forbidden は「誰かは分かるが権限が無い」の意味）
    #
    # 【respond_to で分岐する理由】
    #   このアプリは同じRailsが2種類の応答を返す:
    #     ・ブラウザが直接開いた   → HTMLを返したい
    #     ・Vueのfetchが呼んだ     → JSONを返したい
    #   fetchに対してHTMLのログイン画面を返しても、
    #   JavaScript側はJSONを期待しているのでパースに失敗して
    #   意味不明なエラーになる。要求された形式で返すのが正しい。
    respond_to do |format|
      format.json { render json: { error: "ログインが必要です" }, status: :unauthorized }
      # HTMLの場合はSPAの入口を返す。Vue側のルーターが
      # 「未ログインならログイン画面を出す」判断をする。
      format.html { render "pages/index", status: :unauthorized }
    end
  end

  # --------------------------------------------------------------------------
  # ログインさせる
  # --------------------------------------------------------------------------
  def sign_in(user)
    # 【reset_session が最重要】← 書き忘れると脆弱性になる
    #
    #   これを呼ぶと、今のセッションを破棄して新しいセッションIDを発行する。
    #
    #   【セッション固定攻撃（Session Fixation）とは】
    #     ① 攻撃者が先にサイトを訪れ、セッションID "abc123" をもらう
    #     ② 被害者に「このリンクから入って」と、IDを固定させる細工をする
    #     ③ 被害者がそのIDのままログインする
    #     ④ サーバーは "abc123" にログイン済みの印を付ける
    #     ⑤ 攻撃者は自分の持っている "abc123" でアクセス
    #        → ログイン済みとして扱われ、被害者になりすませてしまう
    #
    #   ログインの瞬間にIDを作り直せば、攻撃者が知っている
    #   古いIDは無効になり、この攻撃は成立しなくなる。
    #
    #   「ログイン成功時は必ずセッションを作り直す」は認証実装の鉄則。
    reset_session

    # 新しいセッションにユーザーIDを記録する。これでログイン状態になる。
    session[:user_id] = user.id

    # メモ化した値も更新しておく。
    # これが無いと、ログイン直後の同じリクエスト内で current_user を呼んだとき
    # 「まだ未ログイン」という古い結果が返ってしまう。
    @current_user = user
  end

  # --------------------------------------------------------------------------
  # ログアウトさせる
  # --------------------------------------------------------------------------
  def sign_out
    # 【session[:user_id] = nil ではなく reset_session を使う理由】
    #   ユーザーIDだけ消しても、セッションIDや他の値は残る。
    #   セッションを丸ごと作り直す方が、消し忘れが原理的に起きない。
    #
    #   ログアウトは「安全側に倒す」場面なので、
    #   細かく消すより全部捨てる方が正しい。
    reset_session
    @current_user = nil
  end
end
