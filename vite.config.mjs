// ============================================================================
// vite.config.mjs — Vite（フロントエンドのビルドツール）の設定
//
// 【Viteとは】
//   .vue ファイルやJavaScriptを、ブラウザが理解できる形に変換するツール。
//
// 【なぜ変換が必要か】
//   ブラウザは .vue ファイルを直接読めない。
//   また import で分割されたファイル群をそのまま読ませると、
//   読み込み回数が膨大になって遅い。
//   まとめて1つにし、ブラウザが読める形に変えるのがビルドツールの役目。
//
// ----------------------------------------------------------------------------
// 【このプロジェクトの構成：HMR 方式（開発サーバー常駐）】
// ----------------------------------------------------------------------------
//   config/vite.json で
//     "autoBuild": false, "skipProxy": false
//   としており、vite コンテナで開発サーバーを常駐させている。
//
//   HMR = Hot Module Replacement。ページ全体を読み込み直さず、
//   変更したモジュールだけを差し替える。保存した瞬間に画面が変わり、
//   入力途中のフォームの内容やスクロール位置も保持される。
//
//   通信は2系統に分かれる。ここが理解の要点:
//
//     ① アセット（.vue や .js の中身）… Rails が中継する
//        ブラウザ → localhost:3000/vite-dev/... → Rails → vite:3036
//        【なぜ Rails を通すか】ブラウザから見て全てが同一オリジンになり、
//        Cookie・CORS の例外を作らずに済む。CLAUDE.md の
//        「同一オリジン」の判断をHMR導入で崩さないための構成。
//
//     ② HMR の通知（WebSocket）… ブラウザから vite へ直結する
//        ブラウザ → ws://localhost:3036 → vite コンテナ
//        【なぜ直結が必要か】①の中継をしている vite_ruby の
//        DevServerProxy は Rack::Proxy 製で、WebSocket の
//        Upgrade を扱えない。中継させようとすると接続が確立せず、
//        「画面が自動更新されない」という形で失敗する。
//        そのため ws だけは経路を分け、下の hmr 設定で
//        「ブラウザはこのポートへ繋げ」と明示している。
//
//   【元は autoBuild 方式だった】
//     Rails が更新を検知してその場でビルドする方式で、コンテナは1つ
//     少なかったが、反映のたびにブラウザの再読み込みが必要だった。
//     画面を作り込む段階に入ったためHMRへ切り替えた。
// ============================================================================
import { defineConfig } from 'vite'
import RubyPlugin from 'vite-plugin-ruby'
import vue from '@vitejs/plugin-vue'

export default defineConfig({
  plugins: [
    // Rails と Vite を繋ぐプラグイン。
    // config/vite.json を読み、出力先を Rails の public/ 配下に合わせる。
    RubyPlugin(),

    // .vue ファイル（テンプレート・スクリプト・スタイルが1ファイルに
    // まとまった形式）を解釈できるようにするプラグイン。
    // これが無いと .vue を読んだ時点で構文エラーになる。
    vue(),
  ],

  server: {
    // ------------------------------------------------------------------------
    // 【host: '0.0.0.0' について】
    //   Viteの開発サーバーは既定で localhost だけを見る。
    //   しかし「コンテナの中のlocalhost」はコンテナ内部しか指さないため、
    //   ホストPCのブラウザからも web コンテナからも繋がらない。
    //   0.0.0.0 は「どのネットワーク経由の接続も受ける」の意味で、
    //   Railsを -b 0.0.0.0 で起動しているのと同じ理由。
    // ------------------------------------------------------------------------
    host: '0.0.0.0',

    // ------------------------------------------------------------------------
    // 【strictPort】ポートが埋まっていたら黙って別ポートへ移らず、起動を失敗させる。
    //   Viteの既定は「3036が使用中なら3037で起動」という親切な挙動だが、
    //   この構成では Rails が vite:3036 を決め打ちで中継するため、
    //   ずれた瞬間にアセットが404になる。しかもViteは正常に動いている
    //   ように見えるので原因が分かりにくい。早く失敗させた方が良い。
    // ------------------------------------------------------------------------
    strictPort: true,

    // ------------------------------------------------------------------------
    // 【allowedHosts】Viteが受け付ける Host ヘッダのホワイトリスト。
    //   Vite 5.4以降、DNSリバインディング攻撃への対策として
    //   localhost 以外のHostヘッダを持つリクエストを既定で拒否する。
    //
    //   このアプリでは Rails の中継を通る際、vite_ruby が Host ヘッダを
    //   コンテナ名 "vite" に書き換える（dev_server_proxy.rb を参照）。
    //   そのため素のままだとViteに弾かれ、アセットが403になる。
    //   中継元は同一Docker内部ネットワークの web コンテナだけなので、
    //   その名前を明示的に許可する。true（全許可）にはしない。
    // ------------------------------------------------------------------------
    allowedHosts: ['vite', 'localhost'],

    // ------------------------------------------------------------------------
    // 【hmr】変更通知を運ぶ WebSocket の接続先をブラウザに教える設定。
    //
    //   ブラウザは localhost:3000（Rails）でページを開いているので、
    //   放っておくと ws://localhost:3000 に繋ごうとして失敗する。
    //   RailsのHMR中継は不可能（ファイル冒頭の②を参照）なので、
    //   「Viteへ直接繋げ」と clientPort で明示する。
    //
    //   host はコンテナ名ではなく localhost であることが重要。
    //   この値を解釈するのはコンテナの中ではなく、
    //   ホストPCのブラウザだから。"vite" と書くと名前解決できない。
    // ------------------------------------------------------------------------
    hmr: {
      host: 'localhost',
      protocol: 'ws',
      clientPort: 3036,
    },

    // ------------------------------------------------------------------------
    // 【ファイル監視の設定】
    //   usePolling は「変更を定期的に見に行く」方式。
    //   通常はOSの通知機構を使う方が効率的だが、
    //   Docker（特にWindows/Mac）ではホストとコンテナの間で
    //   その通知が伝わらないことがある。
    //
    //   ポーリングはCPUを少し使うが、確実に変更を検知できる。
    //   「保存しても反映されない」を避けるための保険。
    // ------------------------------------------------------------------------
    watch: {
      usePolling: true,
      interval: 300,
    },
  },
})
