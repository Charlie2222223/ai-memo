// ============================================================================
// vite.config.mjs — Vite（フロントエンドのビルドツール）の設定
//
// 【Viteとは】
//   .vue ファイルやJavaScriptを、ブラウザが理解できる形に変換するツール。
//
// 【なぜ変換が必要か】
//   ブラウザは .vue ファイルを直接読めない。
//   また import で分割されたファイル群をそのまま読ませると、
//   読み込み回数が膨大になって遅い。
//   まとめて1つにし、ブラウザが読める形に変えるのがビルドツールの役目。
//
// ----------------------------------------------------------------------------
// 【このプロジェクトの構成：autoBuild 方式】
// ----------------------------------------------------------------------------
//   config/vite.json で
//     "autoBuild": true, "skipProxy": true
//   としているため、次のように動く:
//
//     ① ブラウザが localhost:3000 を開く
//     ② Rails が app/frontend/ の更新を検知
//     ③ 変更があればその場でビルドし public/vite-dev/ に出力
//     ④ ビルド済みのJSをRailsが配信
//
//   → Viteの開発サーバーを別に起動する必要がない。
//     コンテナが1つ減り、構成が単純になる。
//
//   【この方式の使い勝手】
//     コードを保存 → ブラウザを再読み込み → 変更が反映される。
//     ビルドは1〜2秒程度。
//
//   【HMR（保存した瞬間に反映）を使いたくなったら】
//     Viteの開発サーバーを別プロセスで動かし、
//     config/vite.json の skipProxy を false にして
//     Railsに中継させる構成に変える。
//     再読み込み不要になり、入力中のフォームの内容も保持される。
//
//     ただしDockerだとコンテナ間のホスト名解決とWebSocketのポート指定が
//     絡んで設定が増えるため、まずは単純な今の形で始めるのが無難。
//     画面を作り込む段階になって煩わしくなったら切り替えるとよい。
// ============================================================================
import { defineConfig } from 'vite'
import RubyPlugin from 'vite-plugin-ruby'
import vue from '@vitejs/plugin-vue'

export default defineConfig({
  plugins: [
    // Rails と Vite を繋ぐプラグイン。
    // config/vite.json を読み、出力先を Rails の public/ 配下に合わせる。
    RubyPlugin(),

    // .vue ファイル（テンプレート・スクリプト・スタイルが1ファイルに
    // まとまった形式）を解釈できるようにするプラグイン。
    // これが無いと .vue を読んだ時点で構文エラーになる。
    vue(),
  ],

  server: {
    // ------------------------------------------------------------------------
    // 【host: '0.0.0.0' について】
    //   今の autoBuild 方式では開発サーバーを起動しないので使われないが、
    //   将来HMRに切り替えたときに必要になる設定。
    //
    //   Viteの開発サーバーは既定で localhost だけを見る。
    //   しかし「コンテナの中のlocalhost」はコンテナ内部しか指さないため、
    //   ホストPCのブラウザからは繋がらない。
    //   0.0.0.0 は「どのネットワーク経由の接続も受ける」の意味で、
    //   Railsを -b 0.0.0.0 で起動しているのと同じ理由。
    // ------------------------------------------------------------------------
    host: '0.0.0.0',

    // ------------------------------------------------------------------------
    // 【ファイル監視の設定】
    //   usePolling は「変更を定期的に見に行く」方式。
    //   通常はOSの通知機構を使う方が効率的だが、
    //   Docker（特にWindows/Mac）ではホストとコンテナの間で
    //   その通知が伝わらないことがある。
    //
    //   ポーリングはCPUを少し使うが、確実に変更を検知できる。
    //   「保存しても反映されない」を避けるための保険。
    // ------------------------------------------------------------------------
    watch: {
      usePolling: true,
      interval: 300,
    },
  },
})
