# ============================================================================
# rails_helper.rb — テスト全体の共通設定
#
# 【役割】
#   各 *_spec.rb の先頭で require されるファイル。
#   Railsを読み込み、テスト全体で使う設定をここにまとめる。
#
# 【spec_helper.rb との違い】
#   spec_helper … RSpec単体の設定（Railsに依存しない）
#   rails_helper … Railsを読み込んだ上での設定  ← 通常こちらを使う
# ============================================================================

require "spec_helper"

# ============================================================================
# 【最重要】テスト環境を強制する
# ============================================================================
# rspec-rails が生成する既定のコードは
#     ENV["RAILS_ENV"] ||= "test"
# だが、これは Docker では危険な罠になる。
#
# 【||= の意味】「まだ設定されていなければ設定する」。
#   つまり既に値が入っていれば何もしない。
#
# 【何が起きたか】
#   docker-compose.yml で RAILS_ENV: development を渡している。
#   そのため ||= は何もせず、RAILS_ENV は development のまま。
#   結果、テストが development 環境として起動し、
#   memo_test ではなく memo_development に接続していた。
#
#   （このとき Host Authorization も development の設定が効くため、
#     リクエストスペックが軒並み 403 で落ちるという
#     一見無関係な症状として現れた。原因の特定が難しい種類の不具合）
#
# 【なぜ深刻か】
#   use_transactional_fixtures によって各テストはロールバックされるので
#   今回は実害が出なかったが、
#   ・トランザクションの外で動く処理（DDL、別プロセス）
#   ・DatabaseCleaner で truncate する設定にした場合
#   では、開発中のデータが実際に消える。
#
# 【対策】||= ではなく = で無条件に上書きする。
#   テストが development 環境で走ることは、
#   どんな状況でも正当化できない。
#   「設定されていたら尊重する」ではなく「必ずtestにする」が正しい。
ENV["RAILS_ENV"] = "test"

require_relative "../config/environment"

# 【安全装置】本番環境でテストを走らせようとしたら即座に止める。
#   テストはDBを空にしてから始まるので、
#   本番で実行すると全データが消える。
#   「起きたら取り返しがつかない」種類の事故なので、
#   コードで物理的に防いでおく。
abort("The Rails environment is running in production mode!") if Rails.env.production?

require "rspec/rails"

# ----------------------------------------------------------------------------
# 外部への通信を遮断する
# ----------------------------------------------------------------------------
# 【なぜ必須か】← このアプリでは特に重要
#   このアプリはClaude APIを呼ぶ。テスト中に本物のAPIを叩くと:
#     ① 実行のたびに課金される
#     ② 1回10秒かかり、テストが遅くて実行しなくなる
#     ③ AIの返答は毎回違うので、結果が安定しない
#        （同じコードなのに通ったり落ちたりする＝テストの意味が消える）
#     ④ ネットが繋がらない場所で開発できない
#
#   disable_net_connect! を書くと、テスト中に外部へHTTP通信しようとした
#   瞬間に例外が出る。「うっかり本物を呼んでいた」を確実に検知できる。
#
# 【allow_localhost: true の理由】
#   自分自身（テスト用のサーバー）への通信まで塞ぐと、
#   ブラウザを使うテストが動かなくなるため、localhostだけ許可する。
require "webmock/rspec"
WebMock.disable_net_connect!(allow_localhost: true)

# ----------------------------------------------------------------------------
# spec/support 以下のファイルを自動で読み込む
# ----------------------------------------------------------------------------
# テスト用の補助メソッド（ログイン処理など）を置く場所。
# 【なぜ分けるか】全spec共通で使うものを rails_helper に直接書くと
#   このファイルが肥大化する。役割ごとにファイルを分けておく。
Rails.root.glob("spec/support/**/*.rb").sort_by(&:to_s).each { |f| require f }

# ----------------------------------------------------------------------------
# 未適用のマイグレーションがあれば自動で反映する
# ----------------------------------------------------------------------------
# 【なぜ必要か】マイグレーションを書いた後にテストを流すと、
#   テスト用DBだけ古い構造のままで「カラムが無い」エラーになる。
#   この行があると自動で追いついてくれる。
begin
  ActiveRecord::Migration.maintain_test_schema!
rescue ActiveRecord::PendingMigrationError => e
  abort e.to_s.strip
end

RSpec.configure do |config|
  config.fixture_paths = [ Rails.root.join("spec/fixtures") ]

  # --------------------------------------------------------------------------
  # 各テストをトランザクションで囲む
  # --------------------------------------------------------------------------
  # 【動き】1つのテストが始まる前にトランザクションを開始し、
  #   終わったらロールバック（取り消し）する。
  #   テスト中に作ったデータは、そのテストが終わると自動で消える。
  #
  # 【なぜ重要か】テスト同士が影響し合わなくなる。
  #   もしデータが残ると、
  #   「Aのテストで作ったユーザーのせいでBのテストが落ちる」
  #   「実行順を変えると結果が変わる」といった、
  #   原因の分かりにくい不具合が起きる。
  #
  #   各テストが「空のDBから始まる」ことを保証すると、
  #   テストを単独でも全体でも同じ結果で実行できる。
  config.use_transactional_fixtures = true

  # --------------------------------------------------------------------------
  # ファイルの置き場所からテストの種類を推測させる
  # --------------------------------------------------------------------------
  # spec/requests/ に置けば type: :request、
  # spec/models/ に置けば type: :model が自動で付く。
  #
  # 【type が何を変えるか】request 型なら get / post といった
  #   HTTPリクエストを送るメソッドが使えるようになる。
  #   毎回 type: :request と書かずに済む。
  config.infer_spec_type_from_file_location!

  # --------------------------------------------------------------------------
  # FactoryBot のメソッドを直接使えるようにする
  # --------------------------------------------------------------------------
  # これが無いと FactoryBot.create(:user) と毎回書く必要があるが、
  # 設定すると create(:user) と短く書ける。
  #
  # 【FactoryBot とは】テスト用データの「作り方の型紙」を
  #   1箇所に定義しておく仕組み。
  #   User.create!(email: ..., password: ...) を各テストに書くと、
  #   カラムが増えるたび全テストの修正が必要になる。
  #   型紙を1つ直せば済むようにするのが目的。
  config.include FactoryBot::Syntax::Methods

  # ログイン操作をまとめたヘルパー（spec/support/auth_helper.rb）を
  # request 型のテストで使えるようにする。
  config.include AuthHelper, type: :request

  # バックトレースからRails本体の行を除外して読みやすくする。
  config.filter_rails_from_backtrace!
end
