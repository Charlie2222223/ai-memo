# ============================================================================
# User のファクトリ（テスト用データの型紙）
#
# 【使い方】
#   create(:user)                      … DBに保存された User を作る
#   build(:user)                       … メモリ上だけの User を作る（保存しない）
#   create(:user, email: "a@b.com")    … 一部だけ上書きして作る
#
# 【create と build の使い分け】
#   DBへの保存は時間がかかる。検証のテストのように
#   保存しなくても確認できるものは build を使うとテストが速くなる。
# ============================================================================
FactoryBot.define do
  factory :user do
    # --------------------------------------------------------------------------
    # メールアドレスを毎回変える
    # --------------------------------------------------------------------------
    # 【sequence とは】呼ばれるたびに n が 1, 2, 3... と増える仕組み。
    #   結果として user1@example.com, user2@example.com ... が作られる。
    #
    # 【なぜ固定値ではいけないか】
    #   users.email にユニーク制約を掛けたので、
    #   固定値だと2人目を作った瞬間に必ず失敗する。
    #   「1つのテストで複数ユーザーを作る」場面は頻出する
    #   （例：他人のデータが見えないことの確認には2人必要）。
    #
    # 【example.com を使う理由】
    #   RFC 2606 で「文書・例示専用」と予約されているドメイン。
    #   実在しないことが保証されているので、
    #   テストが誤って実在の誰かにメールを送る事故が起きない。
    sequence(:email) { |n| "user#{n}@example.com" }

    # AuthHelper と同じ値を使う。
    # 【定数を参照する理由】両方に文字列を直書きすると、
    #   片方だけ変えたときにログインできなくなり、
    #   原因が「パスワード不一致」だと気付くまで時間を溶かす。
    password { AuthHelper::TEST_PASSWORD }
  end
end
