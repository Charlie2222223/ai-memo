# ============================================================================
# AuthHelper — テストからログインするための補助メソッド
#
# 【なぜ必要か】
#   認証が必要なAPIをテストするとき、毎回
#     post "/api/session", params: { email: ..., password: ... }
#   と書くのは冗長で、ログインの手順が変わったとき
#   全テストを直す羽目になる。
#
#   1箇所にまとめておけば、仕様変更にもここだけで追随できる。
#
# 【テスト用コードも「重複を避ける」対象】
#   テストコードは書き捨てだと思われがちだが、
#   実際は本番コードより長生きすることも多い。
#   読みやすさと保守性は本番コードと同じ基準で考える。
# ============================================================================
module AuthHelper
  # 既定のパスワード。
  # 【なぜ12文字以上か】User モデルで最低12文字の検証を掛けたため、
  #   これより短いとテスト用ユーザーの作成自体が失敗する。
  TEST_PASSWORD = "test-password-1234".freeze

  # --------------------------------------------------------------------------
  # 実際にログインAPIを叩いてログイン状態を作る
  # --------------------------------------------------------------------------
  # 【なぜ session[:user_id] を直接書き換えないのか】← 重要な判断
  #   テストからセッションを直接いじる方法もあるが、それだと
  #   「ログイン処理そのもの」を通らない。
  #
  #   実際のAPIを叩けば、
  #     ・パスワード照合が動くか
  #     ・reset_session でセッションが作り直されるか
  #     ・Cookieが正しく発行されるか
  #   まで含めて検証される。
  #
  #   テストは「本番と同じ経路」を通るほど信頼できる。
  #   近道をすると、その近道の部分の不具合を検知できなくなる。
  def sign_in_as(user, password: TEST_PASSWORD)
    post "/api/session", params: { email: user.email, password: password }
    # 【ここで検証も入れる理由】
    #   ログインに失敗しているのに気付かず後続を実行すると、
    #   本当は「ログインできていない」のに
    #   「権限チェックが動いていない」と誤読してしまう。
    #   前提が崩れた時点で止める。
    raise "テスト用のログインに失敗しました: #{response.status} #{response.body}" unless response.status == 200
    user
  end

  # --------------------------------------------------------------------------
  # レスポンスのJSONをRubyのハッシュに変換する
  # --------------------------------------------------------------------------
  # 【symbolize_names: true の意味】
  #   JSONのキーを文字列 "id" ではなくシンボル :id に変換する。
  #   json[:id] と書けるようになり、Rubyらしく読みやすい。
  def json_body
    JSON.parse(response.body, symbolize_names: true)
  end
end
