# ============================================================================
# routes.rb — URLとコントローラの対応表
#
# 【ルーティングとは】
#   ブラウザから来たリクエストを見て、
#   「どのコントローラのどのメソッドを呼ぶか」を決める交通整理。
#
#     POST /api/session  →  SessionsController#create
#     ~~~~ ~~~~~~~~~~~~     ~~~~~~~~~~~~~~~~~ ~~~~~~
#     HTTPメソッド パス        コントローラ      アクション
#
#   HTTPメソッド（GET/POST/DELETE等）とパスの「組み合わせ」で決まる。
#   同じ /api/session でも GET と DELETE で別の処理に振り分けられる。
# ============================================================================
Rails.application.routes.draw do
  # --------------------------------------------------------------------------
  # ヘルスチェック（Railsが自動生成したもの）
  # --------------------------------------------------------------------------
  # アプリが生きているかを確認するための専用URL。
  # 【何に使うか】Fly.ioなどのホスティングは、定期的にここを叩いて
  #   200が返るか確認する。返らなければ「落ちた」と判断して
  #   自動で再起動してくれる。段階8のデプロイで実際に使う。
  #
  # 【認証を掛けてはいけない】監視する側はログインできないので、
  #   認証必須にすると常に401が返り「ずっと落ちている」と誤判定される。
  #   Rails内蔵のコントローラなので ApplicationController を
  #   継承しておらず、そもそも認証は掛かっていない。
  get "up" => "rails/health#show", as: :rails_health_check

  # --------------------------------------------------------------------------
  # API（Vueがデータをやり取りする窓口）
  # --------------------------------------------------------------------------
  # 【なぜ /api/ という接頭辞を付けるのか】
  #   ① 画面用のURLとデータ用のURLが一目で区別できる
  #   ② 後から「/api/ で始まるものだけ別の扱いにする」といった
  #      まとめた制御がしやすい（ログ・レート制限・認証方式の変更など）
  #   ③ Vue Router が使うパス（/terms/5 など）と衝突しない
  #      ← これが実務上いちばん効く。両方が / 直下だと必ずぶつかる
  scope :api, defaults: { format: :json } do
    # ------------------------------------------------------------------------
    # セッション（ログイン・ログアウト・ログイン確認）
    # ------------------------------------------------------------------------
    # 【resource（単数形）と resources（複数形）の違い】← よく混同する
    #   resources :terms  … 単語は何個もある → URLにIDが要る
    #                        /api/terms/5
    #   resource :session … セッションは「今の自分の1つ」しかない → IDが要らない
    #                        /api/session
    #
    #   「自分のログイン状態」は1人につき1つなので、単数形が正しい。
    #   単数形にすると index アクションが生成されない
    #   （一覧が存在しない概念なので当然）。
    #
    # 【only: で絞る理由】
    #   何も指定しないと new / edit まで生成される。
    #   new/edit は「HTMLのフォーム画面を返す」ためのもので、
    #   画面をVueが作るこの構成では絶対に使わない。
    #
    #   使わないURLを開けておくと、
    #   ・攻撃対象の面積が広がる
    #   ・rails routes の出力が読みにくくなる
    #   ので、必要なものだけ明示する。
    resource :session, only: [ :show, :create, :destroy ]

    # ------------------------------------------------------------------------
    # 単語（段階3で実装）
    # ------------------------------------------------------------------------
    # resources :terms は7つのURLをまとめて定義する:
    #   GET    /api/terms      → index   一覧
    #   POST   /api/terms      → create  新規登録
    #   GET    /api/terms/:id  → show    詳細
    #   PATCH  /api/terms/:id  → update  更新
    #   DELETE /api/terms/:id  → destroy 削除
    #   （new / edit はHTMLフォーム用なので除外）
    resources :terms, only: [ :index, :show, :create, :update, :destroy ] do
      # 【member とは】「特定の1件に対する操作」を追加する書き方。
      #   ここで定義したURLには :id が含まれる。
      #     POST /api/terms/5/regenerate
      #
      #   対になる collection は「一覧全体に対する操作」で、IDが入らない。
      #
      # 【regenerate（再生成）が必要な理由】
      #   AI呼び出しは失敗しうる（APIの障害、ネットワーク断、レート制限）。
      #   失敗した単語を捨てて登録し直させるのは不親切なので、
      #   「もう一度やってみる」ボタンを用意する。
      #   段階5でジョブを実装したときに中身を書く。
      member do
        post :regenerate
      end
    end

    # ------------------------------------------------------------------------
    # タグ（段階3で実装）
    # ------------------------------------------------------------------------
    # 絞り込み用のタグ一覧を返すだけなので index のみ。
    # タグの作成は単語の登録時にまとめて行うため、専用のURLは要らない。
    resources :tags, only: [ :index ]
  end

  # --------------------------------------------------------------------------
  # Sidekiq の管理画面
  # --------------------------------------------------------------------------
  # 【何が見られるか】
  #   実行待ち・処理中・成功数・失敗したジョブの一覧と、その例外の内容。
  #   「非同期処理で今なにが起きているか」が目で見える。
  #   Q8でSidekiqを選んだ理由の一つがこれ。
  #
  # 【認証で保護している理由】← 極めて重要
  #   この画面からはジョブの中身が読め、削除も再実行もできる。
  #   Q5でインターネットに公開すると決めた以上、
  #   無防備に置くと誰でもジョブを操作できてしまう。
  #
  #   実際、認証を掛け忘れた /sidekiq が公開されている事例は
  #   検索エンジンで見つかるほど多い。
  #
  # 【constraints の意味】
  #   このルートに到達してよい条件を指定する。
  #   ラムダに渡される request からセッションを読み、
  #   ログイン済みでなければ「そんなルートは無い」ものとして扱われる。
  #
  #   【なぜ authenticate ではなくこの書き方か】
  #   Sidekiq::Web は Rails のコントローラではなく独立したRackアプリなので、
  #   before_action が使えない。ルーティングの段階で止める必要がある。
  require "sidekiq/web"

  constraints(->(request) { request.session[:user_id].present? }) do
    mount Sidekiq::Web => "/sidekiq"
  end

  # --------------------------------------------------------------------------
  # SPAの入口（この定義は必ず最後に置く）
  # --------------------------------------------------------------------------
  # 【root とは】"/" にアクセスされたときの行き先。
  root "pages#index"

  # 【この1行が SPA の要】
  #   ブラウザで直接 https://memo.fly.dev/terms/5 を開いたり、
  #   その状態でリロードしたときの動作を決める。
  #
  #   Vue Router は「ブラウザの中だけで」URLを書き換えている。
  #   サーバーはそのURLを知らないので、リロードすると
  #   「/terms/5 なんてルートは無い」と 404 になってしまう。
  #
  #   そこで「他のどれにも当てはまらないGETリクエストは、
  #   全部SPAの入口HTMLを返す」という受け皿を最後に置く。
  #   Vueが起動してからURLを見て、正しい画面を描画してくれる。
  #
  # 【各部分の意味】
  #   *path        … 任意の文字列にマッチする（ワイルドカード）
  #   via: :all    … GET/POST等すべてのHTTPメソッド
  #   format: false … ".json" などの拡張子部分もパスの一部として扱う
  #                    （これが無いと /terms/5.5 のようなURLで誤動作する）
  #
  # 【なぜ最後でなければならないか】
  #   ルーティングは上から順に照合し、最初に一致したものが採用される。
  #   この受け皿を上に書くと、/api/terms も含めた全リクエストが
  #   ここで捕まってしまい、APIが一切動かなくなる。
  #
  # 【なぜ /api/ を除外しているか】
  #   存在しないAPIのURLを叩かれたとき、HTMLを返すと
  #   Vue側は「JSONが返るはず」と思っているのでパースに失敗し、
  #   「Unexpected token '<'」という原因の分かりにくいエラーになる。
  #   API配下は素直に404（JSON）を返させる。
  match "*path", to: "pages#index", via: :all, format: false,
        constraints: ->(req) { !req.path.start_with?("/api/") }
end
