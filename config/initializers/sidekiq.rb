# ============================================================================
# Sidekiq の設定
#
# 【Sidekiq とは】
#   Rubyで最も広く使われている非同期ジョブ処理の仕組み。
#   Redisを待ち行列（キュー）として使い、
#   別プロセスのワーカーがジョブを取り出して実行する。
#
# 【Active Job との関係】
#   Active Job … Railsが用意した「ジョブの共通インターフェース」
#   Sidekiq    … 実際に動かす実装（バックエンド）
#
#   Active Job を通して書いておけば、
#   将来 Sidekiq から別の実装に乗り換えるとき、
#   ジョブのコード自体は変えずに済む。
# ============================================================================

# ----------------------------------------------------------------------------
# ジョブを積む側（Railsサーバー）の設定
# ----------------------------------------------------------------------------
Sidekiq.configure_client do |config|
  config.redis = {
    url: ENV.fetch("REDIS_URL", "redis://localhost:6379/0"),

    # 【接続プールの大きさ】
    #   Railsは複数のリクエストを同時に処理するので、
    #   Redisへの接続も同時に必要になる。
    #   Railsのスレッド数と揃えておくと、待ちが発生しにくい。
    size: ENV.fetch("RAILS_MAX_THREADS", 5).to_i
  }
end

# ----------------------------------------------------------------------------
# ジョブを実行する側（Sidekiqワーカー）の設定
# ----------------------------------------------------------------------------
Sidekiq.configure_server do |config|
  config.redis = { url: ENV.fetch("REDIS_URL", "redis://localhost:6379/0") }

  # --------------------------------------------------------------------------
  # 【死んだジョブの保管量と期間】
  #   リトライを使い切って失敗したジョブは「Dead」として保管される。
  #   管理画面から中身を見て、原因を調べたり手動で再実行したりできる。
  #
  #   既定は 10,000件 / 180日。
  #   このアプリは失敗をDB（terms.error_message と api_call_logs）にも
  #   記録しているので、Redis側でそこまで長く持つ必要はない。
  #   Redisはメモリ上で動くため、溜め込むとメモリを圧迫する。
  #
  # 【設定の書き方に注意】← ここで一度間違えた箇所
  #   config.dead_max_jobs = 1000 と書くと
  #     undefined method `dead_max_jobs=' for an instance of Sidekiq::Config
  #   になる。Sidekiq 7 の Config は個別のセッターを持たず、
  #   ハッシュのように config[:キー] = 値 で設定する形になっている。
  #
  #   バージョンによって設定方法が変わる典型例。
  #   ネットの記事をそのまま貼ると、古い書き方で動かないことがある。
  config[:dead_max_jobs] = 1_000
  config[:dead_timeout_in_seconds] = 7 * 24 * 60 * 60   # 7日
end
