# ============================================================================
# セッションCookieの設定
#
# 【initializers ディレクトリとは】
#   ここに置いたファイルは、Rails起動時に自動で読み込まれる。
#   アプリ全体の設定を書く場所。
#
# 【このファイルで決めること】
#   ログイン状態を保持するCookieに、どんな安全策を付けるか。
#   Cookieは「ブラウザに預ける小さなメモ」なので、
#   何も指定しないと盗まれる・偽装される余地が残る。
# ============================================================================

Rails.application.config.session_store :cookie_store,

  # ----------------------------------------------------------------------------
  # Cookieの名前
  # ----------------------------------------------------------------------------
  # 【先頭に __Host- を付けている理由】← 単なる名前ではなく仕様上の意味がある
  #   ブラウザは "__Host-" で始まるCookieに対して、
  #   次の条件を満たさない限り保存を拒否するという決まりがある:
  #     ・Secure が付いている（HTTPS必須）
  #     ・Path が "/" である
  #     ・Domain が指定されていない
  #
  #   なぜこれが効くのか:
  #     Domain指定が無い ＝ サブドメインからこのCookieを上書きできない。
  #     もし evil.memo.fly.dev のような場所を攻撃者に取られても、
  #     memo.fly.dev のセッションCookieを差し替えられない。
  #
  #   名前の規則をブラウザ側が強制してくれる仕組みで、
  #   設定ミスを防ぐ効果もある（条件を満たさなければ黙って保存されない）。
  #
  # 【開発環境では使えない】
  #   __Host- は Secure（HTTPS）が必須。ローカルは http なので、
  #   本番だけこの名前にする。
  key: Rails.env.production? ? "__Host-memo_session" : "_memo_session",

  # ----------------------------------------------------------------------------
  # httponly: true — JavaScriptからCookieを読めなくする
  # ----------------------------------------------------------------------------
  # 【なぜ必須か】← XSSに対する最後の防衛線
  #   XSS（クロスサイトスクリプティング）とは、
  #   攻撃者のJavaScriptをあなたのページ上で実行させる攻撃。
  #
  #   このアプリには具体的なリスクがある:
  #     AIが生成した解説文をそのまま画面に表示する。
  #     もしAIの出力に <script> タグが混ざっていて、
  #     それをそのままHTMLとして埋め込むと、実行されてしまう。
  #
  #   httponly が無い場合、攻撃者のスクリプトは
  #     document.cookie で全Cookieを読み取り
  #     → 自分のサーバーへ送信
  #     → セッションを乗っ取れる
  #
  #   httponly: true なら、document.cookie に一切現れない。
  #   ブラウザがHTTP通信のときだけ自動で付けてくれるので、
  #   アプリの動作には支障がない。
  #
  # 【Q7でセッションCookieを選び、JWTを選ばなかった理由がこれ】
  #   JWTを localStorage に置く方式だと、
  #   JavaScriptから読める場所に置く以外に選択肢がない。
  #   XSSが1つでもあれば、そのトークンは即座に盗まれる。
  #   Cookie + httponly なら、XSSがあってもトークン自体は守られる。
  httponly: true,

  # ----------------------------------------------------------------------------
  # same_site: :lax — 他サイトからのリクエストにCookieを付けない
  # ----------------------------------------------------------------------------
  # 【CSRFへの構造的な対策】
  #   前提として、ブラウザは「そのドメイン宛」であれば
  #   どこから発火したリクエストでも自動でCookieを付けてしまう。
  #   これがCSRF攻撃の土台になっている。
  #
  #   SameSite はその挙動そのものを制限する指定:
  #     :strict … 他サイトからの遷移では一切送らない
  #               → 安全だが、メールのリンクから来ると
  #                 ログイン済みなのに未ログイン扱いになり不便
  #     :lax    … 他サイトからでも「普通のリンク（GET）」なら送る。
  #               ただしPOST/DELETEなど変更を伴うものには送らない
  #     :none   … 常に送る（＝実質無防備。Secure必須）
  #
  #   :lax なら、攻撃者のページから勝手にPOSTされても
  #   Cookieが付かないので、サーバーは未ログインとして扱う。
  #   使い勝手を保ちながら、危険な操作だけ止められる。
  #
  # 【Q7で同一オリジンを選んだ効果がここに出ている】
  #   もしフロントとAPIを別ドメインに分けていたら、
  #   正規のリクエストすら「他サイトから」の扱いになり、
  #   :none にせざるを得なかった。
  #   ＝ CSRFへの防御を自ら捨てることになっていた。
  #   同一オリジンにしたおかげで :lax が使える。
  same_site: :lax,

  # ----------------------------------------------------------------------------
  # secure — HTTPS接続のときだけCookieを送る
  # ----------------------------------------------------------------------------
  # 【なぜ必要か】
  #   http（暗号化なし）で通信すると、
  #   同じWi-Fiにいる第三者が通信内容を覗ける。
  #   Cookieが平文で流れれば、そのまま盗まれてログインし放題になる。
  #
  #   カフェや駅の公衆Wi-Fiで使うことを考えると現実的な脅威。
  #
  # 【開発では false にする理由】
  #   ローカルは http://localhost なので、true にすると
  #   Cookieが一切保存されず、ログインできなくなる。
  #   環境で切り替える。
  secure: Rails.env.production?
